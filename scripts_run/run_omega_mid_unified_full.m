    error('run_omega_mid_unified_full:GenerationPublishFailed', ...
        'Could not publish the staged generation: %s',message);
end
validate_omega_mid_publication_generation( ...
    staged.generation_dir,staged.generation_manifest_sha256);
fprintf('Published immutable Omega_mid generation %s.\n', ...
    staged.generation_id);
end


