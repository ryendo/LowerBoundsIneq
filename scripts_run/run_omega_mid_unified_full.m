    error('run_omega_mid_unified_full:UnsafeGenerationCleanup', ...
        'Refusing cleanup with an unexpected manifest name.');
end
validate_omega_mid_publication_generation( ...
    pathname,expected_sha256, ...
    'staging_pointer_sha256',staging_pointer_sha256);
rmdir(pathname,'s');
end


