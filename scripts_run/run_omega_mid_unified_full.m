%RUN_OMEGA_MID_UNIFIED_FULL  Production Omega_mid certificate for J1/J2.
%
% This is the ver10 liulabhpc wrapper.  It covers every row of
% inputs/cell_def.csv, uses one shared eigenvalue computation per cell for
% J1 and J2, and writes atomic resumable chunk checkpoints.  The driver
% refuses to start a complete interval run from a dirty Git checkout.

project_root = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(project_root,'scripts_run'));
results_root = fullfile(project_root,'results');
target_J1 = fullfile(results_root,'J1_OmegaMid.csv');
target_J2 = fullfile(results_root,'J2_OmegaMid.csv');
summary_json = fullfile(results_root,'verification_summary.json');
summary_markdown = fullfile(results_root,'verification_summary.md');
current_pointer = fullfile(results_root,'omega_mid_current.json');
public_targets = { ...
    target_J1,target_J2,summary_json,summary_markdown,current_pointer};
publication_journal = fullfile( ...
    results_root,'.omega_mid_publication_journal.mat');
local_recover_publication(publication_journal,public_targets);
local_release_destination();

manifest = run_omega_mid_unified_parallel( ...
    'mode','interval', ...
    'workers',20, ...
    'input_file',fullfile(project_root,'inputs','cell_def.csv'), ...
    'chunk_size',256, ...
    'checkpoint_every',32, ...
    'max_subdivision_depth',8, ...
    'max_fem_refinement_level',2, ...
    'minimum_cr_mesh_size',0.005, ...
    'minimum_lg_mesh_size',0.025, ...
    'run_name','ver10_omega_mid_unified_prod', ...
    'resume',true, ...
    'retry_failed',true);

local_validate_geometric_coverage( ...
    manifest,project_root,fullfile(project_root,'inputs','cell_def.csv'));
if ~manifest.complete_certificate
    error('run_omega_mid_unified_full:IncompleteCertificate', ...
        ['The unified production run did not produce a complete, clean, ', ...
         'strict interval certificate.  Public result files were not ', ...
         'modified.']);
end
source_artifacts = validate_omega_mid_unified_artifacts( ...
    manifest,project_root,'require_complete',true);

% Publish only after the manifest has certified both exact input IDs and
% rigorous geometric coverage of the actual Omega_mid region.
% The legacy public validator consumes these canonical paths and requires
% status=ok, finite J_lower>0, and verified=1 on every input cell id.
source_J1 = source_artifacts.paths.J1_csv;
source_J2 = source_artifacts.paths.J2_csv;
local_validate_public_pair(source_J1,source_J2, ...
    fullfile(project_root,'inputs','cell_def.csv'));

staged_generation = local_stage_versioned_generation( ...
    project_root,manifest,source_J1,source_J2);
try
    publication = local_begin_publication( ...
        {source_J1,source_J2, ...
         staged_generation.summary_json, ...
         staged_generation.summary_markdown, ...
         staged_generation.pointer_source}, ...
        public_targets,publication_journal,staged_generation);
catch ME
    local_abandon_staged_generation(staged_generation);
    rethrow(ME);
end
try
    validator = VerifyTriangleInequalities();
    validator.run();
    local_validate_public_pair(target_J1,target_J2, ...
        fullfile(project_root,'inputs','cell_def.csv'));
    local_validate_public_summary(summary_json,summary_markdown);
    if ~strcmp(ver10_file_sha256(current_pointer), ...
            staged_generation.pointer_sha256)
        error('run_omega_mid_unified_full:PointerCopyMismatch', ...
            'The staged current-generation pointer changed during copy.');
    end
    local_finalize_staged_generation(staged_generation);
    local_commit_publication(publication);
catch ME
    if strcmp(publication.state,'prepared')
        local_rollback_publication(publication);
    else
        local_cleanup_files(publication.staged);
        local_cleanup_files(publication.backups);
    end
    local_abandon_staged_generation(staged_generation);
    rethrow(ME);
end

fprintf('Omega_mid unified production run finished.\n');
fprintf('complete certificate: %d\n',manifest.complete_certificate);
fprintf('geometric coverage certificate: %d (%s)\n', ...
    manifest.summary.geometric_coverage_certified, ...
    manifest.geometric_coverage.hashes.proof_payload);
fprintf('strict records: %d/%d\n', ...
    manifest.summary.num_strict_records, ...
    manifest.summary.num_selected_cells);
fprintf('minimum J1 lower: %.17g\n', ...
    manifest.summary.minimum_J1_lower);
fprintf('minimum J2 lower: %.17g\n', ...
    manifest.summary.minimum_J2_lower);


function coverage_path = local_validate_geometric_coverage( ...
    manifest,project_root,input_file)
if ~isstruct(manifest) ...
        || ~isfield(manifest,'geometric_coverage') ...
        || ~isfield(manifest,'summary') ...
        || ~isfield(manifest.summary,'geometric_coverage_certified') ...
        || ~logical(manifest.summary.geometric_coverage_certified) ...
        || ~isfield(manifest,'files') ...
        || ~isfield(manifest.files,'geometric_coverage_json') ...
        || ~isfield(manifest,'hashes') ...
        || ~isfield(manifest.hashes,'geometric_coverage_json')
    error('run_omega_mid_unified_full:MissingGeometricCoverage', ...
        ['The unified manifest lacks a certified geometric Omega_mid ', ...
         'coverage artifact.  Exact cell IDs alone are insufficient.']);
end
coverage = manifest.geometric_coverage;
if ~isfield(coverage,'schema') ...
        || ~strcmp(coverage.schema, ...
            'lowerboundsineq.omega_mid_geometric_coverage.v1') ...
        || ~isfield(coverage,'complete') || ~logical(coverage.complete) ...
        || ~isfield(coverage,'rigorous') || ~logical(coverage.rigorous) ...
        || ~isfield(coverage,'status') ...
        || ~strcmp(coverage.status,'certified') ...
        || ~isfield(coverage,'input') ...
        || ~isfield(coverage.input,'sha256') ...
        || ~isfield(coverage,'proof') ...
        || ~isfield(coverage.proof,'decimal_topology_exact') ...
        || ~logical(coverage.proof.decimal_topology_exact) ...
        || ~isfield(coverage.proof,'binary_double_endpoint_roundtrip') ...
        || logical(coverage.proof.binary_double_endpoint_roundtrip) ...
        || ~isfield(coverage.proof,'arbitrary_tolerance_used') ...
        || logical(coverage.proof.arbitrary_tolerance_used) ...
        || ~isfield(coverage,'hashes') ...
        || ~isfield(coverage.hashes,'proof_payload') ...
        || numel(coverage.hashes.proof_payload) ~= 64
    error('run_omega_mid_unified_full:BadGeometricCoverage', ...
        'The geometric coverage payload is incomplete or non-rigorous.');
end
input_sha256 = ver10_file_sha256(input_file);
if ~strcmp(coverage.input.sha256,input_sha256) ...
        || ~isfield(manifest,'input') ...
        || ~isfield(manifest.input,'sha256') ...
        || ~strcmp(manifest.input.sha256,input_sha256)
    error('run_omega_mid_unified_full:CoverageInputMismatch', ...
        ['The geometric coverage certificate is not bound to the ', ...
         'published input CSV.']);
end
relative = char(manifest.files.geometric_coverage_json);
if isempty(relative) || local_is_absolute_path(relative) ...
        || ~isempty(regexp(strrep(relative,'\','/'), ...
            '(^|/)\.\.($|/)','once'))
    error('run_omega_mid_unified_full:BadCoveragePath', ...
        'The geometric coverage manifest path is not repository-relative.');
end
coverage_path = fullfile(project_root,relative);
if ~exist(coverage_path,'file') ...
        || ~strcmp(ver10_file_sha256(coverage_path), ...
            manifest.hashes.geometric_coverage_json)
    error('run_omega_mid_unified_full:CoverageHashMismatch', ...
        'The geometric coverage JSON is missing or has the wrong SHA-256.');
end
disk = jsondecode(fileread(coverage_path));
if ~isfield(disk,'schema') || ~strcmp(disk.schema,coverage.schema) ...
        || ~isfield(disk,'complete') || ~logical(disk.complete) ...
        || ~isfield(disk,'rigorous') || ~logical(disk.rigorous) ...
        || ~isfield(disk,'input') || ~isfield(disk.input,'sha256') ...
        || ~strcmp(disk.input.sha256,input_sha256) ...
        || ~isfield(disk,'hashes') ...
        || ~isfield(disk.hashes,'proof_payload') ...
        || ~strcmp(disk.hashes.proof_payload, ...
            coverage.hashes.proof_payload)
    error('run_omega_mid_unified_full:CoveragePayloadMismatch', ...
        ['The hashed geometric coverage JSON does not reproduce the ', ...
         'certificate embedded in the unified manifest.']);
end
end


function tf = local_is_absolute_path(pathname)
pathname = char(pathname);
tf = startsWith(pathname,filesep) ...
    || ~isempty(regexp(pathname,'^[A-Za-z]:[\\/]','once'));
end


function local_validate_public_pair(source_J1,source_J2,input_file)
expected_table = readtable(input_file);
expected_ids = sort(double(expected_table.i(:)));
J1 = local_validate_public_csv(source_J1,'J1',expected_ids);
J2 = local_validate_public_csv(source_J2,'J2',expected_ids);
[~,order1] = sort(double(J1.cell_id));
[~,order2] = sort(double(J2.cell_id));
common_fields = {'method','LG_escalation_policy', ...
    'fem_refinement_scheme','fem_refinement_used', ...
    'max_fem_refinement_level_allowed', ...
    'minimum_cr_mesh_size_allowed','minimum_lg_mesh_size_allowed', ...
    'max_cr_refinement_level_used','max_lg_refinement_level_used', ...
    'minimum_cr_mesh_size_used','minimum_lg_mesh_size_used', ...
    'lambda1_lower','LG_rho_lower', ...
    'LG_ritz_upper','LG_separation_margin_lower','LG_mu_upper', ...
    'LG_B_verified_spd', ...
    'shared_eigenvalue_computation','strict_checks_passed', ...
    'subdivision_used','leaf_count','max_leaf_depth', ...
    'max_subdivision_depth_allowed','evaluated_node_count', ...
    'spectral_solve_count','LG_shift_method', ...
    'LG_fallback_used','LG_fallback_reason', ...
    'eigenvalue_total_seconds','LG_CR_shift_seconds', ...
    'LG_fallback_node_count','LG_analytic_shift_node_count', ...
    'LG_CR_Liu_shift_node_count','direct_CR_node_count'};
for k = 1:numel(common_fields)
    name = common_fields{k};
    left = J1.(name)(order1,:);
    right = J2.(name)(order2,:);
    if ~isequaln(left,right)
        error('run_omega_mid_unified_full:UnsharedSpectralRows', ...
            'J1/J2 differ in the shared spectral column %s.',name);
    end
end
end


function table_value = local_validate_public_csv( ...
    filename,conjecture,expected_ids)
if ~exist(filename,'file')
    error('run_omega_mid_unified_full:MissingArtifact', ...
        'Cannot publish missing artifact: %s',filename);
end
table_value = readtable(filename,'TextType','string');
required = {'conjecture','cell_id','verified','J_lower','status', ...
    'note','run_timestamp','certificate_status','rigorous', ...
    'method','LG_escalation_policy','fem_refinement_scheme', ...
    'fem_refinement_used','max_fem_refinement_level_allowed', ...
    'minimum_cr_mesh_size_allowed','minimum_lg_mesh_size_allowed', ...
    'max_cr_refinement_level_used','max_lg_refinement_level_used', ...
    'minimum_cr_mesh_size_used','minimum_lg_mesh_size_used', ...
    'lambda1_lower','LG_rho_lower', ...
    'LG_ritz_upper','LG_separation_margin_lower','LG_mu_upper', ...
    'LG_B_verified_spd', ...
    'subdivision_used','leaf_count','max_leaf_depth', ...
    'max_subdivision_depth_allowed','evaluated_node_count', ...
    'spectral_solve_count', ...
    'LG_shift_method','LG_fallback_used','LG_fallback_reason', ...
    'eigenvalue_total_seconds','LG_CR_shift_seconds', ...
    'LG_fallback_node_count','LG_analytic_shift_node_count', ...
    'LG_CR_Liu_shift_node_count','direct_CR_node_count', ...
    'shared_eigenvalue_computation','strict_checks_passed'};
if ~all(ismember(required,table_value.Properties.VariableNames))
    error('run_omega_mid_unified_full:BadPublicSchema', ...
        '%s lacks a required public or provenance column.',filename);
end
ids = double(table_value.cell_id(:));
if height(table_value) ~= numel(expected_ids) ...
        || numel(unique(ids)) ~= numel(ids) ...
        || ~isequal(sort(ids),expected_ids)
    error('run_omega_mid_unified_full:BadPublicCoverage', ...
        '%s does not cover the exact input cell-id set.',filename);
end
if ~all(strcmpi(strtrim(string(table_value.conjecture)),conjecture)) ...
        || ~all(double(table_value.verified) == 1) ...
        || ~all(isfinite(double(table_value.J_lower)) ...
            & double(table_value.J_lower) > 0) ...
        || ~all(strcmpi(strtrim(string(table_value.status)),'ok')) ...
        || ~all(strcmp( ...
            strtrim(string(table_value.certificate_status)), ...
            'certified_interval')) ...
        || ~all(double(table_value.rigorous) == 1) ...
        || ~all(isfinite(double(table_value.lambda1_lower)) ...
            & double(table_value.lambda1_lower) > 0) ...
        || ~all(double(table_value.shared_eigenvalue_computation) == 1) ...
        || ~all(double(table_value.strict_checks_passed) == 1)
    error('run_omega_mid_unified_full:BadPublicCertificate', ...
        '%s contains a non-strict or nonfinite certificate row.',filename);
end
methods = strtrim(string(table_value.method));
if ~all(ismember(methods,["CR","LG","SUBDIVISION"]))
    error('run_omega_mid_unified_full:BadPublicMethod', ...
        '%s contains an unknown eigenvalue method.',filename);
end
if ~all(strcmp(strtrim(string(table_value.LG_escalation_policy)), ...
        'LG-input-or-terminal-depth-after-CR-refinement-v1'))
    error('run_omega_mid_unified_full:BadLGEscalationPolicy', ...
        '%s does not use the production LG escalation policy.',filename);
end
if ~all(strcmp(strtrim(string(table_value.fem_refinement_scheme)), ...
        'dyadic-CR-then-terminal-LG-v1'))
    error('run_omega_mid_unified_full:BadFEMRefinementPolicy', ...
        '%s does not use the production FEM refinement scheme.', ...
        filename);
end
subdivision = methods == "SUBDIVISION";
leaf_count = double(table_value.leaf_count);
max_leaf_depth = double(table_value.max_leaf_depth);
evaluated_node_count = double(table_value.evaluated_node_count);
spectral_solve_count = double(table_value.spectral_solve_count);
max_fem_allowed = double( ...
    table_value.max_fem_refinement_level_allowed);
min_cr_allowed = double(table_value.minimum_cr_mesh_size_allowed);
min_lg_allowed = double(table_value.minimum_lg_mesh_size_allowed);
max_cr_used = double(table_value.max_cr_refinement_level_used);
max_lg_used = double(table_value.max_lg_refinement_level_used);
min_cr_used = double(table_value.minimum_cr_mesh_size_used);
min_lg_used = double(table_value.minimum_lg_mesh_size_used);
fem_refinement_used = double(table_value.fem_refinement_used);
subdivision_used = double(table_value.subdivision_used);
max_subdivision_allowed = double( ...
    table_value.max_subdivision_depth_allowed);
if any(~isfinite(evaluated_node_count) ...
        | evaluated_node_count < 1 ...
        | evaluated_node_count ~= floor(evaluated_node_count) ...
        | ~isfinite(spectral_solve_count) ...
        | spectral_solve_count < evaluated_node_count ...
        | spectral_solve_count ~= floor(spectral_solve_count) ...
        | ~isfinite(leaf_count) | leaf_count < 1 ...
        | leaf_count ~= floor(leaf_count) ...
        | ~isfinite(max_leaf_depth) | max_leaf_depth < 0 ...
        | max_leaf_depth ~= floor(max_leaf_depth) ...
        | ~isfinite(max_subdivision_allowed) ...
        | max_subdivision_allowed < 0 ...
        | max_subdivision_allowed ~= floor(max_subdivision_allowed) ...
        | max_leaf_depth > max_subdivision_allowed ...
        | ~ismember(subdivision_used,[0,1]) ...
        | ~isfinite(max_fem_allowed) ...
        | max_fem_allowed < 0 ...
        | max_fem_allowed ~= floor(max_fem_allowed) ...
        | ~isfinite(min_cr_allowed) | min_cr_allowed <= 0 ...
        | ~isfinite(min_lg_allowed) | min_lg_allowed <= 0 ...
        | ~isfinite(max_cr_used) | max_cr_used < 0 ...
        | max_cr_used > max_fem_allowed ...
        | max_cr_used ~= floor(max_cr_used) ...
        | ~isfinite(max_lg_used) | max_lg_used < -1 ...
        | max_lg_used > max_fem_allowed ...
        | max_lg_used ~= floor(max_lg_used) ...
        | ~isfinite(min_cr_used) | min_cr_used <= 0 ...
        | fem_refinement_used ...
            ~= (max_cr_used > 0 | max_lg_used > 0) ...
        | spectral_solve_count ...
            > 2*(max_fem_allowed+1).*evaluated_node_count) ...
        || any(double(table_value.LG_CR_Liu_shift_node_count) > 0 ...
            & (~isfinite(min_lg_used) | min_lg_used <= 0)) ...
        || any(double(table_value.LG_B_verified_spd) ~= 1)
    error('run_omega_mid_unified_full:BadFEMRefinementSummary', ...
        '%s contains inconsistent FEM refinement diagnostics.', ...
        filename);
end
if any(double(table_value.subdivision_used(subdivision)) ~= 1 ...
        | leaf_count(subdivision) <= 1 ...
        | max_leaf_depth(subdivision) < 1 ...
        | evaluated_node_count(subdivision) ...
            ~= (4*leaf_count(subdivision)-1)/3 ...
        | spectral_solve_count(subdivision) ...
            < evaluated_node_count(subdivision))
    error('run_omega_mid_unified_full:BadSubdivisionCertificate', ...
        '%s contains an inconsistent subdivision summary.',filename);
end
shift_method = strtrim(string(table_value.LG_shift_method));
valid_shift = ismember(shift_method, ...
    ["CR-Liu","not-applicable"]);
eigenvalue_seconds = double(table_value.eigenvalue_total_seconds);
cr_shift_seconds = double(table_value.LG_CR_shift_seconds);
fallback_used = double(table_value.LG_fallback_used);
fallback_reason = strtrim(string(table_value.LG_fallback_reason));
fallback_reason(ismissing(fallback_reason)) = "";
fallback_nodes = double(table_value.LG_fallback_node_count);
analytic_nodes = double(table_value.LG_analytic_shift_node_count);
cr_liu_nodes = double(table_value.LG_CR_Liu_shift_node_count);
direct_cr_nodes = double(table_value.direct_CR_node_count);
uses_lg = cr_liu_nodes > 0;
node_counts = [fallback_nodes,analytic_nodes, ...
    cr_liu_nodes,direct_cr_nodes];
if any(~valid_shift) ...
        || any(~isfinite(eigenvalue_seconds) ...
            | eigenvalue_seconds < 0) ...
        || any(~isfinite(cr_shift_seconds) | cr_shift_seconds < 0) ...
        || any(~isfinite(node_counts(:))) ...
        || any(node_counts(:) < 0) ...
        || any(node_counts(:) ~= floor(node_counts(:))) ...
        || any(fallback_nodes ~= 0) ...
        || any(analytic_nodes ~= 0) ...
        || any(cr_liu_nodes+direct_cr_nodes ...
            ~= evaluated_node_count) ...
        || any(fallback_used ~= 0) ...
        || any(strlength(fallback_reason) > 0) ...
        || any(methods == "CR" ...
            & (shift_method ~= "not-applicable" | uses_lg)) ...
        || any(methods == "LG" ...
            & (shift_method ~= "CR-Liu" | ~uses_lg)) ...
        || any(uses_lg & shift_method ~= "CR-Liu") ...
        || any(~uses_lg & shift_method ~= "not-applicable") ...
        || any(uses_lg & (max_lg_used < 0 ...
            | ~isfinite(min_lg_used) | min_lg_used <= 0)) ...
        || any(~uses_lg & (max_lg_used ~= -1 ...
            | ~isnan(min_lg_used)))
    error('run_omega_mid_unified_full:BadLGShiftDiagnostics', ...
        '%s contains inconsistent LG shift or timing diagnostics.', ...
        filename);
end
lg = uses_lg;
direct_lg = methods == "LG";
rho = double(table_value.LG_rho_lower);
ritz = double(table_value.LG_ritz_upper);
separation = double(table_value.LG_separation_margin_lower);
mu_upper = double(table_value.LG_mu_upper);
% For SUBDIVISION rows these are extrema across distinct LG leaves.  The
% positive aggregate separation margin certifies every leaf; min(rho) need
% not exceed max(Ritz) when those extrema occur on different leaves.
if any(~isfinite(rho(lg)) | rho(lg) <= 0 ...
        | ~isfinite(ritz(lg)) | ritz(lg) <= 0 ...
        | ~isfinite(separation(lg)) | separation(lg) <= 0 ...
        | ~isfinite(mu_upper(lg)) | mu_upper(lg) >= 0) ...
        || any(rho(direct_lg) <= ritz(direct_lg))
    error('run_omega_mid_unified_full:BadPublicLGCertificate', ...
        '%s contains a row that fails strict LG conditions.',filename);
end
end


function publication = local_begin_publication( ...
    sources,targets,journal_path,staged_generation)
publication = struct();
publication.schema = ...
    'lowerboundsineq.omega_mid_publication_journal.v2';
publication.state = 'preparing';
publication.sources = sources;
publication.targets = targets;
publication.journal_path = journal_path;
publication.staged = cell(size(sources));
publication.backups = cell(size(targets));
publication.had_original = false(size(targets));
publication.generation = local_journal_generation(staged_generation);

if exist(journal_path,'file')
    error('run_omega_mid_unified_full:UnrecoveredJournal', ...
        ['A prior publication journal still exists.  Recovery must ', ...
         'finish before another publication begins.']);
end
try
    for k = 1:numel(sources)
        directory = fileparts(targets{k});
        publication.staged{k} = [tempname(directory),'.csv'];
        [ok,message] = copyfile( ...
            sources{k},publication.staged{k},'f');
        if ~ok
            error('run_omega_mid_unified_full:StageFailed', ...
                'Could not stage %s: %s',targets{k},message);
        end
    end
    for k = 1:numel(targets)
        if exist(targets{k},'file')
            [~,~,extension] = fileparts(targets{k});
            publication.backups{k} = ...
                [tempname(fileparts(targets{k})),extension];
            [ok,message] = copyfile( ...
                targets{k},publication.backups{k},'f');
            if ~ok
                error('run_omega_mid_unified_full:BackupFailed', ...
                    'Could not back up %s: %s',targets{k},message);
            end
            publication.had_original(k) = true;
        end
    end
    publication.state = 'prepared';
    local_save_publication_journal(publication);
    for k = 1:numel(sources)
        [ok,message] = movefile( ...
            publication.staged{k},targets{k},'f');
        if ~ok
            error('run_omega_mid_unified_full:PublishFailed', ...
                'Could not publish %s: %s',targets{k},message);
        end
    end
catch ME
    if strcmp(publication.state,'prepared')
        local_rollback_publication(publication);
    else
        % No canonical target is touched until the durable prepared journal
        % exists.  During preparation, clean only temporary copies.
        local_cleanup_publication_generation(publication);
        local_cleanup_files(publication.staged);
        local_cleanup_files(publication.backups);
    end
    rethrow(ME);
end
end


function local_recover_publication(journal_path,expected_targets)
if ~exist(journal_path,'file')
    return;
end
try
    payload = load(journal_path,'publication');
catch ME
    error('run_omega_mid_unified_full:UnreadableJournal', ...
        'Cannot read the interrupted publication journal: %s',ME.message);
end
if ~isfield(payload,'publication') ...
        || ~isstruct(payload.publication)
    error('run_omega_mid_unified_full:BadJournal', ...
        'The interrupted publication journal has no valid payload.');
end
publication = payload.publication;
if ~strcmp(local_publication_field( ...
            publication,'schema',''), ...
        'lowerboundsineq.omega_mid_publication_journal.v2') ...
        || ~strcmp(local_publication_field( ...
            publication,'journal_path',''),journal_path) ...
        || ~isequal(local_publication_field( ...
            publication,'targets',{}),expected_targets)
    error('run_omega_mid_unified_full:BadJournal', ...
        'The interrupted publication journal has unexpected targets.');
end
local_validate_journal_paths(publication,journal_path);
if ~isfield(publication,'generation') ...
        || ~isstruct(publication.generation)
    error('run_omega_mid_unified_full:BadJournal', ...
        'The interrupted journal lacks staged-generation recovery data.');
end
local_validate_journal_generation(publication.generation,journal_path);
state = local_publication_field(publication,'state','');
if strcmp(state,'committed')
    local_assert_committed_generation(publication);
    local_cleanup_files(local_publication_field( ...
        publication,'staged',{}));
    local_cleanup_files(local_publication_field( ...
        publication,'backups',{}));
    local_delete_if_present(journal_path);
    fprintf('Recovered cleanup from a committed Omega_mid publication.\n');
elseif strcmp(state,'rolled_back')
    local_cleanup_publication_generation(publication);
    local_cleanup_files(local_publication_field( ...
        publication,'staged',{}));
    local_cleanup_files(local_publication_field( ...
        publication,'backups',{}));
    local_delete_if_present(journal_path);
    fprintf('Recovered cleanup from a rolled-back Omega_mid publication.\n');
elseif strcmp(state,'prepared')
    local_rollback_publication(publication);
    fprintf('Rolled back an interrupted Omega_mid publication.\n');
else
    error('run_omega_mid_unified_full:BadJournalState', ...
        'The interrupted publication journal is not recoverable.');
end
end


