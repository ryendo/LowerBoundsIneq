        || ~strcmp(generation.publication_root,expected_root) ...
        || ~isfield(generation,'temporary_dir') ...
        || ~strcmp(fileparts(generation.temporary_dir),expected_root) ...
        || ~isfield(generation,'generation_dir') ...
