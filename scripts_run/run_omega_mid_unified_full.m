    'verification_summary_markdown',names.summary_markdown, ...
    'omega_mid_geometric_coverage_manifest',names.coverage, ...
    'omega_mid_unified_manifest',names.unified, ...
    'omega_mid_unified_results_mat',names.results_mat, ...
    'config_mat',names.config_mat);
generation.sha256 = struct( ...
    'J1_OmegaMid_csv_gz',J1_gzip.file_sha256, ...
    'J1_OmegaMid_csv_expanded_content', ...
        J1_gzip.expanded_content_sha256, ...
    'J2_OmegaMid_csv_gz',J2_gzip.file_sha256, ...
    'J2_OmegaMid_csv_expanded_content', ...
        J2_gzip.expanded_content_sha256, ...
    'verification_summary_json', ...
        ver10_file_sha256(paths.summary_json), ...
    'verification_summary_markdown', ...
        ver10_file_sha256(paths.summary_markdown), ...
    'omega_mid_geometric_coverage_manifest', ...
        ver10_file_sha256(paths.coverage), ...
    'omega_mid_unified_manifest', ...
        ver10_file_sha256(paths.unified), ...
    'omega_mid_unified_results_mat', ...
        ver10_file_sha256(paths.results_mat), ...
    'config_mat',ver10_file_sha256(paths.config_mat));
