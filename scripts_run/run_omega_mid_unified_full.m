    generation,publication.journal_path);
local_remove_bound_generation_if_present( ...
    generation.temporary_dir,generation.manifest_name, ...
    generation.manifest_sha256,generation.staging_pointer_sha256);
local_remove_bound_generation_if_present( ...
    generation.generation_dir,generation.manifest_name, ...
    generation.manifest_sha256,'');
end


function local_assert_committed_generation(publication)
generation = publication.generation;
