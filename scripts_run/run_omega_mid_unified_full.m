local_copy_bound(coverage_source,paths.coverage, ...
    certificate_manifest.hashes.geometric_coverage_json,'coverage');
local_copy_unified(unified_source,paths.unified);
local_copy_bound(mat_source,paths.results_mat, ...
    certificate_manifest.hashes.mat,'results MAT');
local_copy_bound(config_source,paths.config_mat, ...
    certificate_manifest.hashes.config_mat,'config MAT');
validate_omega_mid_unified_artifacts( ...
    certificate_manifest,project_root, ...
    'require_complete',true, ...
    'validate_record_structure',false, ...
    'J1_file',source_J1,'J2_file',source_J2, ...
    'coverage_file',paths.coverage, ...
    'unified_manifest_file',paths.unified, ...
    'mat_file',paths.results_mat,'config_file',paths.config_mat);

generation = struct();
generation.schema = ...
    'lowerboundsineq.omega_mid_publication_generation.v2';
generation.generation_id = generation_id;
generation.created_utc = certificate_manifest.created_utc;
generation.certificate_fingerprint = ...
    certificate_manifest.fingerprint;
