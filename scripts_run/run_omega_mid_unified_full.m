        || ~strcmp(generation.staging_pointer_name, ...
            '.omega_mid_current.json') ...
        || ~isfield(generation,'staging_pointer_sha256') ...
        || isempty(regexp(generation.staging_pointer_sha256, ...
            '^[0-9a-f]{64}$','once'))
    error('run_omega_mid_unified_full:BadJournal', ...
        'The interrupted journal has unsafe generation recovery data.');
end
end


function local_validate_journal_paths(publication,journal_path)
targets = local_publication_field(publication,'targets',{});
backups = local_publication_field(publication,'backups',{});
staged = local_publication_field(publication,'staged',{});
had_original = local_publication_field( ...
    publication,'had_original',[]);
if ~iscell(targets) || ~iscell(backups) || ~iscell(staged) ...
        || numel(backups) ~= numel(targets) ...
        || numel(had_original) ~= numel(targets) ...
        || ~all(ismember(double(had_original(:)),[0,1]))
    error('run_omega_mid_unified_full:BadJournal', ...
        'The interrupted publication journal has incoherent arrays.');
end
allowed_directory = fileparts(journal_path);
temporary_paths = [backups(:);staged(:)];
for k = 1:numel(temporary_paths)
    pathname = temporary_paths{k};
    if isempty(pathname)
        continue;
    end
    if ~ischar(pathname) ...
            || ~strcmp(fileparts(pathname),allowed_directory)
        error('run_omega_mid_unified_full:BadJournal', ...
            ['The interrupted publication journal references a ', ...
             'temporary path outside the public results directory.']);
    end
end
end


function local_save_publication_journal(publication)
journal_path = publication.journal_path;
directory = fileparts(journal_path);
temporary = [tempname(directory),'.mat'];
cleanup = onCleanup(@() local_delete_if_present(temporary));
save(temporary,'publication','-v7');
[ok,message] = movefile(temporary,journal_path,'f');
if ~ok
    error('run_omega_mid_unified_full:JournalWriteFailed', ...
        'Could not publish the rollback journal: %s',message);
end
clear cleanup
end


function local_regenerate_summary( ...
    project_root,J1_file,J2_file,input_file, ...
    summary_json,summary_markdown)
python = getenv('PYTHON');
if isempty(python)
    python = 'python3';
end
script = fullfile(project_root,'scripts_run','compute_stats.py');
command = sprintf([ ...
    '%s %s --j1 %s --j2 %s --input %s ', ...
    '--summary-json %s --summary-markdown %s'], ...
    local_shell_quote(python),local_shell_quote(script), ...
    local_shell_quote(J1_file),local_shell_quote(J2_file), ...
    local_shell_quote(input_file),local_shell_quote(summary_json), ...
    local_shell_quote(summary_markdown));
[status,output] = system(command);
if ~isempty(output)
    fprintf('%s',output);
end
if status ~= 0
    error('run_omega_mid_unified_full:SummaryFailed', ...
        'compute_stats.py exited with status %d.',status);
end
summary = jsondecode(fileread(summary_json));
if ~isfield(summary,'overall') ...
        || ~logical(summary.overall.all_verified)
    error('run_omega_mid_unified_full:SummaryIncomplete', ...
        'The regenerated public summary is not fully verified.');
end
local_validate_public_summary(summary_json,summary_markdown);
end


function local_validate_public_summary(summary_json,summary_markdown)
if ~exist(summary_json,'file') || ~exist(summary_markdown,'file')
    error('run_omega_mid_unified_full:MissingPublicSummary', ...
        'Both public summary artifacts must exist before publication.');
end
summary = jsondecode(fileread(summary_json));
if ~isfield(summary,'overall') ...
        || ~isfield(summary.overall,'all_verified') ...
        || ~logical(summary.overall.all_verified)
    error('run_omega_mid_unified_full:SummaryIncomplete', ...
        'The public JSON summary is not fully verified.');
end
info = dir(summary_markdown);
if isempty(info) || info.bytes < 1
    error('run_omega_mid_unified_full:SummaryIncomplete', ...
        'The public Markdown summary is empty.');
end
end


function local_commit_publication(publication)
publication.state = 'committed';
local_save_publication_journal(publication);
try
    local_cleanup_files(publication.staged);
    local_cleanup_files(publication.backups);
    local_delete_if_present(publication.journal_path);
catch ME
    % The committed journal deliberately remains recoverable on the next
    % invocation; publication itself has already passed every validator.
    warning('run_omega_mid_unified_full:CommitCleanupDeferred', ...
        'Committed publication cleanup was deferred: %s',ME.message);
end
end


function local_rollback_publication(publication)
% Remove a staged or already-renamed generation before restoring canonical
% files.  The journal remains in state=prepared until both operations finish,
% so a hard kill at any point is idempotently recoverable on the next run.
local_cleanup_publication_generation(publication);
failures = {};
for k = 1:numel(publication.targets)
    target = publication.targets{k};
    backup = publication.backups{k};
    if publication.had_original(k) && exist(backup,'file')
        % Copy rather than move so a crash during rollback remains
        % idempotently recoverable from the durable journal.
        [ok,message] = copyfile(backup,target,'f');
        if ~ok
            failures{end+1,1} = sprintf( ... %#ok<AGROW>
                'Could not restore %s: %s',target,message);
        end
    elseif ~publication.had_original(k)
        try
            local_delete_if_present(target);
        catch ME
            failures{end+1,1} = sprintf( ... %#ok<AGROW>
                'Could not remove %s: %s',target,ME.message);
        end
    else
        failures{end+1,1} = sprintf( ... %#ok<AGROW>
            'The backup needed to restore %s is missing.',target);
    end
end
if ~isempty(failures)
    error('run_omega_mid_unified_full:RollbackFailed', ...
        '%s',strjoin(failures,' '));
end
publication.state = 'rolled_back';
local_save_publication_journal(publication);
local_cleanup_files(publication.staged);
local_cleanup_files(publication.backups);
local_delete_if_present(publication.journal_path);
end


function staged = local_stage_versioned_generation( ...
