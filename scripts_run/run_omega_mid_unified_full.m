function local_write_json_atomic(filename,value)
try
    encoded = jsonencode(value,'PrettyPrint',true);
catch
    encoded = jsonencode(value);
end
directory = fileparts(filename);
temporary = [tempname(directory),'.json'];
cleanup = onCleanup(@() local_delete_if_present(temporary));
fid = fopen(temporary,'w');
if fid < 0
    error('run_omega_mid_unified_full:JsonWriteFailed', ...
        'Could not open a temporary JSON publication file.');
end
file_cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',encoded);
clear file_cleanup
[ok,message] = movefile(temporary,filename,'f');
if ~ok
    error('run_omega_mid_unified_full:JsonPublishFailed', ...
        'Could not atomically publish %s: %s',filename,message);
end
clear cleanup
end


function local_delete_if_present(filename)
if exist(filename,'file')
    delete(filename);
end
end


