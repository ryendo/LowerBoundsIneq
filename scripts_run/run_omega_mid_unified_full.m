function local_validate_staged_paths(staged)
if ~isstruct(staged) ...
        || ~isfield(staged,'schema') ...
        || ~strcmp(staged.schema, ...
            'lowerboundsineq.omega_mid_staged_generation.v1') ...
        || ~isfield(staged,'publication_root') ...
        || ~isfield(staged,'temporary_dir') ...
        || ~isfield(staged,'generation_dir') ...
        || ~isfield(staged,'generation_manifest_name') ...
        || ~strcmp(staged.generation_manifest_name, ...
            'publication_manifest.json') ...
        || ~isfield(staged,'generation_manifest_sha256') ...
        || isempty(regexp(staged.generation_manifest_sha256, ...
            '^[0-9a-f]{64}$','once')) ...
        || ~isfield(staged,'pointer_source') ...
        || ~strcmp(staged.pointer_source,fullfile( ...
            staged.temporary_dir,'.omega_mid_current.json')) ...
        || ~isfield(staged,'pointer_sha256') ...
        || isempty(regexp(staged.pointer_sha256, ...
            '^[0-9a-f]{64}$','once')) ...
        || ~startsWith(staged.temporary_dir, ...
            [staged.publication_root,filesep]) ...
        || ~startsWith(staged.generation_dir, ...
            [staged.publication_root,filesep]) ...
        || strcmp(staged.temporary_dir,staged.generation_dir)
    error('run_omega_mid_unified_full:UnsafeStagedGeneration', ...
        'Refusing to alter an unrecognized generation path.');
end
end


function local_cleanup_publication_generation(publication)
