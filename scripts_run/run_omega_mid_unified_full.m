function release = local_release_destination()
repository = strtrim(getenv('VER10_RELEASE_REPOSITORY'));
tag = strtrim(getenv('VER10_RELEASE_TAG'));
parts = regexp(repository, ...
    '^([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)$','tokens','once');
if isempty(parts) ...
        || isempty(regexp(tag,'^[A-Za-z0-9_.-]+$','once'))
    error('run_omega_mid_unified_full:MissingReleaseDestination', ...
        ['Set VER10_RELEASE_REPOSITORY=owner/repo and a safe ', ...
         'VER10_RELEASE_TAG before starting the production run.']);
end
release = struct( ...
    'owner',parts{1},'repo',parts{2}, ...
    'repository',repository,'tag',tag);
end


function local_copy_bound(source,destination,expected_hash,label)
if ~strcmp(ver10_file_sha256(source),expected_hash)
    error('run_omega_mid_unified_full:ManifestHashMismatch', ...
        'The source %s does not match its unified-manifest SHA-256.',label);
end
[ok,message] = copyfile(source,destination,'f');
if ~ok || ~strcmp(ver10_file_sha256(destination),expected_hash)
    error('run_omega_mid_unified_full:GenerationCopyFailed', ...
        'Could not make a hash-identical %s copy: %s',label,message);
end
end


function local_copy_unified(source,destination)
[ok,message] = copyfile(source,destination,'f');
if ~ok || ~strcmp(ver10_file_sha256(source), ...
        ver10_file_sha256(destination))
    error('run_omega_mid_unified_full:GenerationCopyFailed', ...
        'Could not copy the unified manifest exactly: %s',message);
end
end


function local_finalize_staged_generation(staged)
