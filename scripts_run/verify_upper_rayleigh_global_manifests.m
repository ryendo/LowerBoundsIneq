function local_validate_anchor_certificate( ...
        certificate,x_anchor,y_anchor,N_LG,N_rho,bound_order)
context = 'spectral certificate';
local_require(isstruct(certificate) && isscalar(certificate), ...
    'A spectral anchor certificate is not a scalar structure.');
local_require(strcmp(local_text(certificate,'schema',context), ...
        'lowerboundsineq.triangle-spectral-cr-lg-certificate.v1') ...
    && strcmp(local_text(certificate,'method',context), ...
        'Lehmann-Goerisch+conforming-Ritz+CR-Liu') ...
    && local_positive_integer(certificate,'index',context) == 1 ...
    && local_positive_integer(certificate,'N_LG',context) == N_LG ...
    && local_positive_integer(certificate,'N_rho',context) == N_rho ...
    && local_positive_integer(certificate,'bound_order',context) ...
        == bound_order ...
    && local_flag(certificate,'rigorous',context) ...
    && local_flag(certificate,'mesh_used',context), ...
    'A spectral anchor certificate has noncanonical metadata.');
local_require(isfield(certificate,'reference_triangle') ...
    && numel(certificate.reference_triangle) == 6, ...
    'A spectral anchor certificate has no reference triangle.');
triangle = certificate.reference_triangle(:).';
expected = [0,0,1,0,x_anchor,y_anchor];
for k = 1:6
    local_require(I_inf(triangle(k)) == expected(k) ...
        && I_sup(triangle(k)) == expected(k), ...
        'A spectral certificate is attached to the wrong anchor.');
end
required = {'lambda_LG_lower','lambda_Ritz_upper', ...
    'lambda_next_CR_lower','lambda1_LG_lower', ...
    'lambda1_Ritz_upper','lambda2_CR_lower'};
for k = 1:numel(required)
    local_require(isfield(certificate,required{k}) ...
        && isscalar(certificate.(required{k})), ...
        ['A spectral certificate is missing ',required{k},'.']);
end
lower = certificate.lambda_LG_lower;
upper = certificate.lambda_Ritz_upper;
next = certificate.lambda_next_CR_lower;
local_require(isfinite(I_inf(lower)) && I_inf(lower) > 0 ...
    && isfinite(I_sup(upper)) && I_inf(lower) <= I_sup(upper) ...
    && isfinite(I_inf(next)) && I_sup(upper) < I_inf(next), ...
    'A spectral certificate has invalid or unseparated endpoints.');
local_require(I_inf(certificate.lambda1_LG_lower) == I_inf(lower) ...
    && I_sup(certificate.lambda1_Ritz_upper) == I_sup(upper) ...
    && I_inf(certificate.lambda2_CR_lower) == I_inf(next), ...
    'A spectral certificate alias endpoint is inconsistent.');
end


function runtime = local_validate_matching_runtime(records)
first = records{1};
local_require(isstruct(first) && isscalar(first), ...
    'A component runtime record is not a scalar object.');
first_payload = jsonencode(first);
record_sha256 = local_sha256_bytes(uint8(first_payload));
tree_hash = local_sha256(first,'intlab_tree_sha256','runtime');
gmsh_hash = local_sha256(first,'gmsh_binary_sha256','runtime');
file_count = local_positive_integer( ...
    first,'intlab_tree_file_count','runtime');
total_bytes = local_positive_integer( ...
    first,'intlab_tree_total_bytes','runtime');
local_require(local_number(first,'gmsh_version_status','runtime') == 0, ...
    'A component runtime did not resolve a working Gmsh executable.');
for k = 2:numel(records)
    current = records{k};
    local_require(isstruct(current) && isscalar(current) ...
        && strcmp(jsonencode(current),first_payload) ...
        && strcmp(local_sha256(current, ...
            'intlab_tree_sha256','runtime'),tree_hash) ...
        && strcmp(local_sha256(current, ...
            'gmsh_binary_sha256','runtime'),gmsh_hash) ...
        && local_positive_integer(current, ...
            'intlab_tree_file_count','runtime') == file_count ...
        && local_positive_integer(current, ...
            'intlab_tree_total_bytes','runtime') == total_bytes, ...
        ['The new upper-bound components used different complete ', ...
         'runtime records.']);
end
runtime = first;
runtime.record_sha256 = record_sha256;
runtime.trust_boundary = [ ...
    'MATLAB, the byte-identical INTLAB tree, Gmsh, the operating ', ...
    'system, hardware, and SHA-256 are trusted dependencies'];
end


function value = local_read_json(filename,label)
local_require(isfile(filename),['Missing ',label,' manifest.']);
try
    value = jsondecode(fileread(filename));
catch ME
    error('verify_upper_rayleigh_global_manifests:InvalidCertificate', ...
        'Cannot parse the %s manifest: %s',label,ME.message);
end
local_require(isstruct(value) && isscalar(value), ...
    ['The ',label,' manifest root is not an object.']);
end


function local_write_json(filename,value)
directory = fileparts(filename);
if ~isempty(directory) && ~isfolder(directory)
    mkdir(directory);
end
fid = fopen(filename,'w');
if fid < 0
    error('verify_upper_rayleigh_global_manifests:CannotWrite', ...
        'Cannot open %s.',filename);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));
clear cleanup
end


function value = local_struct(parent,name,context)
local_require(isstruct(parent) && isscalar(parent) ...
    && isfield(parent,name) && isstruct(parent.(name)) ...
    && isscalar(parent.(name)),['Missing or invalid ',context,'.',name,'.']);
value = parent.(name);
end


function value = local_text(parent,name,context)
local_require(isstruct(parent) && isscalar(parent) ...
    && isfield(parent,name) ...
    && (ischar(parent.(name)) ...
        || (isstring(parent.(name)) && isscalar(parent.(name)))), ...
    ['Missing or invalid ',context,'.',name,'.']);
value = char(parent.(name));
end


function value = local_sha256(parent,name,context)
value = local_text(parent,name,context);
local_require(~isempty(regexp(value,'^[0-9a-f]{64}$','once')), ...
    ['Invalid SHA-256 field ',context,'.',name,'.']);
end


function value = local_number(parent,name,context)
local_require(isstruct(parent) && isscalar(parent) ...
    && isfield(parent,name) && isnumeric(parent.(name)) ...
    && isreal(parent.(name)) && isscalar(parent.(name)) ...
    && isfinite(double(parent.(name))), ...
    ['Missing or invalid ',context,'.',name,'.']);
value = double(parent.(name));
end


function value = local_positive_integer(parent,name,context)
