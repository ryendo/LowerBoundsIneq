function global_manifest = verify_upper_rayleigh_global_manifests( ...
    thin_manifest_path,compact_manifest_path,residual_manifest_path, ...
    spectral_atlas_path,output_path)
%VERIFY_UPPER_RAYLEIGH_GLOBAL_MANIFESTS Join all three upper-bound covers.
%
% This verifier replays the thin Rayleigh and CR--LG spectral artifacts,
% validates the hashes, scopes, signs, and covers of the affine-atlas and
% residual CSVs through the v1 global verifier, and binds every component.

if nargin < 5
    output_path = '';
end
project_root = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(project_root,'src','degenerate'));
addpath(fullfile(project_root,'scripts_run'));
snapshot = struct( ...
    'thin_manifest',ver10_file_sha256(thin_manifest_path), ...
    'compact_manifest',ver10_file_sha256(compact_manifest_path), ...
    'residual_manifest',ver10_file_sha256(residual_manifest_path), ...
    'spectral_atlas',ver10_file_sha256(spectral_atlas_path));
verification_source_before = ver10_source_provenance(project_root);
verification_hashes_before = local_verifier_hashes(project_root);
local_require(verification_source_before.git_status_available ...
    && ~verification_source_before.git_dirty ...
    && ~isempty(verification_source_before.git_commit), ...
    'The global verifier must run from a clean committed source tree.');

thin_validation = validate_muhat1_rayleigh_certificate( ...
    thin_manifest_path,'require_complete_certificate',true);
local_require(thin_validation.complete ...
    && thin_validation.manifest_complete_certificate, ...
    'The thin Rayleigh artifact is not a complete replayed certificate.');
base = verify_upper_conjecture_global_manifests( ...
    compact_manifest_path,residual_manifest_path,'', ...
    'allow_independent_commits',true);
local_require(base.complete_certificate, ...
    'The affine-atlas/residual certificate is incomplete.');

thin = local_read_json(thin_manifest_path,'thin');
compact = local_read_json(compact_manifest_path,'compact');
residual = local_read_json(residual_manifest_path,'residual');
thin_source = local_struct(thin,'source','thin');
compact_source = local_struct(compact,'source','compact');
residual_source = local_struct(residual,'source','residual');
thin_commit = local_text(thin_source,'git_commit','thin.source');
compact_commit = local_text(compact_source,'git_commit','compact.source');
residual_commit = local_text(residual_source,'git_commit','residual.source');
local_require(strcmp(thin_commit,residual_commit), ...
    ['The newly generated thin and residual components do not use one ', ...
     'source commit.']);
local_require(strcmp(verification_source_before.git_commit,thin_commit), ...
    'The global verifier is not running from the new components'' commit.');

thin_config = local_struct(thin,'config','thin');
thin_y_start = 0;
thin_y_end = local_decimal_text_number( ...
    thin_config,'down_y_max_text','thin.config');
atlas = local_struct(compact,'atlas','compact');
atlas_y_start = local_number(atlas,'y_min','compact.atlas');
atlas_y_end = local_number(atlas,'y_up','compact.atlas');
residual_y_start = local_number( ...
    local_struct(residual,'domain_coverage','residual'), ...
    'JUP_certified_y_start_upper','residual.domain_coverage');
local_require(thin_y_end == 0.19, ...
    'The thin Rayleigh component does not reach the canonical y=0.19.');
local_require(atlas_y_start <= thin_y_end, ...
    'The thin Rayleigh and affine-atlas covers have a gap.');
local_require(residual_y_start < atlas_y_end, ...
    'The affine-atlas and residual covers do not overlap.');

thin_runtime = local_struct(thin,'runtime','thin');
compact_runtime = local_struct(compact,'runtime','compact');
residual_runtime = local_struct(residual,'runtime','residual');
trusted_runtime = local_validate_matching_runtime( ...
    {thin_runtime,residual_runtime});
compact_runtime_record = local_validate_legacy_runtime(compact_runtime);
residual_config = local_struct(residual,'config','residual');
residual_runtime_sha256 = local_sha256_bytes( ...
    uint8(jsonencode(residual_runtime)));
local_require(local_flag(residual, ...
        'runtime_rechecked_after_run','residual') ...
    && strcmp(local_sha256(residual,'runtime_sha256','residual'), ...
        residual_runtime_sha256), ...
    ['The residual artifact does not bind a runtime snapshot that was ', ...
     'rechecked after generation.']);
residual_config_runtime = local_struct( ...
    residual_config,'runtime','residual.config');
local_require(strcmp(jsonencode(residual_config_runtime), ...
        jsonencode(residual_runtime)) ...
    && strcmp(local_sha256(residual_config, ...
        'runtime_sha256','residual.config'),residual_runtime_sha256), ...
    'The residual config and manifest runtime bindings disagree.');
local_require(strcmp(local_text(residual_config, ...
        'worker_runtime_validation_policy','residual.config'), ...
        'full-runtime-json-all-workers-before-and-after-dispatch-v1'), ...
    'The residual config has an unsupported worker-runtime policy.');
residual_worker_runtime = local_struct( ...
    residual,'worker_runtime_validation','residual');
ver10_validate_worker_runtime_record( ...
    residual_worker_runtime,residual_runtime_sha256,[], ...
    'residual worker runtime validation');
expected_atlas_sha256 = local_sha256( ...
    residual_config,'spectral_atlas_sha256','residual.config');
global_replay_runtime_before = ver10_runtime_metadata();
global_replay_runtime_before_payload = jsonencode( ...
    global_replay_runtime_before);
global_replay_runtime_sha256 = local_sha256_bytes( ...
    uint8(global_replay_runtime_before_payload));
local_require(strcmp(global_replay_runtime_before_payload, ...
        jsonencode(thin_runtime)) ...
    && strcmp(global_replay_runtime_sha256, ...
        trusted_runtime.record_sha256), ...
    'The current replay runtime does not match the component runtime.');
spectral = local_validate_spectral_atlas( ...
    spectral_atlas_path,expected_atlas_sha256,thin_commit, ...
    thin_runtime,trusted_runtime.record_sha256);
global_replay_runtime_after = ver10_runtime_metadata();
global_replay_runtime_after_payload = jsonencode( ...
    global_replay_runtime_after);
global_replay_runtime_after_sha256 = local_sha256_bytes( ...
    uint8(global_replay_runtime_after_payload));
local_require(strcmp(global_replay_runtime_before_payload, ...
        global_replay_runtime_after_payload) ...
    && strcmp(global_replay_runtime_sha256, ...
        global_replay_runtime_after_sha256), ...
    'The numerical runtime changed during the spectral replay.');
verification_source_after = ver10_assert_source_unchanged( ...
    project_root,verification_source_before);

thin_summary = local_struct(thin,'summary','thin');
thin_hashes = local_struct(thin,'hashes','thin');
global_manifest = struct();
global_manifest.schema = ...
    'lowerboundsineq.siudeja-upper-global-rayleigh.manifest.v2';
global_manifest.theorem = ...
    ['lambda1(T) <= pi^2*P(T)^2/(12*A(T)^2) ', ...
     '+sqrt(3)*pi^2/(3*A(T)) for every triangle T'];
global_manifest.rigor = ...
    'certified_interval_execution_with_thin_and_spectral_replay';
global_manifest.complete_certificate = true;
global_manifest.source = struct( ...
    'thin_git_commit',thin_commit, ...
    'affine_git_commit',compact_commit, ...
    'residual_git_commit',residual_commit, ...
    'spectral_atlas_git_commit',thin_commit, ...
    'component_commits_are_independent',~strcmp(thin_commit,compact_commit), ...
    'all_components_clean',true, ...
    'all_components_unchanged_after_run',true);
global_manifest.cover = struct( ...
    'thin_y_closed_hull',[thin_y_start,thin_y_end], ...
    'affine_y_closed_hull',[atlas_y_start,atlas_y_end], ...
    'residual_y_start',residual_y_start, ...
    'thin_affine_overlap',[atlas_y_start,thin_y_end], ...
    'affine_residual_overlap',[residual_y_start,atlas_y_end], ...
    'normalized_domain_complete',true);
global_manifest.margins = struct( ...
    'thin_functional_upper_display',local_number( ...
        thin_summary,'max_down_scaled_upper_display','thin.summary'), ...
    'thin_functional_upper_hex',local_text( ...
        thin_summary,'max_down_scaled_upper_hex','thin.summary'), ...
    'affine_margin_lower',local_number( ...
        local_struct(base,'margins','base'), ...
        'compact_lower','base.margins'), ...
    'residual_JUP_upper',local_number( ...
        local_struct(base,'margins','base'), ...
        'residual_JUP_upper','base.margins'));
local_require(global_manifest.margins.thin_functional_upper_display < 0 ...
    && global_manifest.margins.affine_margin_lower > 0 ...
    && global_manifest.margins.residual_JUP_upper < 0, ...
    'A global upper-bound margin has the wrong strict sign.');
global_manifest.counts = struct( ...
    'thin_s_cells',thin_validation.number_of_s_cells, ...
    'thin_down_cells',thin_validation.number_of_down_cells, ...
    'affine_cells',local_number(atlas,'number_of_cells','compact.atlas'), ...
    'spectral_anchor_certificates',spectral.num_certificates, ...
    'spectral_anchor_certificates_replayed',spectral.num_replayed);
global_manifest.inputs = struct( ...
    'thin_manifest_sha256',snapshot.thin_manifest, ...
    'thin_coefficients_csv_sha256',local_sha256( ...
        thin_hashes,'coefficients_csv','thin.hashes'), ...
    'thin_cells_csv_sha256',local_sha256( ...
        thin_hashes,'cells_csv','thin.hashes'), ...
    'thin_down_cells_csv_sha256',local_sha256( ...
        thin_hashes,'down_cells_csv','thin.hashes'), ...
    'compact_manifest_sha256',snapshot.compact_manifest, ...
    'compact_csv_sha256',local_text( ...
        local_struct(base,'inputs','base'), ...
        'compact_csv_sha256','base.inputs'), ...
    'residual_manifest_sha256',snapshot.residual_manifest, ...
    'residual_csv_sha256',local_text( ...
        local_struct(base,'inputs','base'), ...
        'residual_csv_sha256','base.inputs'), ...
    'spectral_atlas_sha256',expected_atlas_sha256);
global_manifest.trusted_runtime = trusted_runtime;
global_manifest.global_replay_runtime_sha256 = ...
    global_replay_runtime_sha256;
global_manifest.global_replay_runtime_rechecked_after_run = true;
global_manifest.global_replay_worker_runtime_validation = ...
    spectral.worker_runtime_validation;
global_manifest.affine_component_runtime = compact_runtime_record;
global_manifest.verification_source = struct( ...
    'git_commit',verification_source_after.git_commit, ...
    'git_status_available',verification_source_after.git_status_available, ...
    'git_dirty',verification_source_after.git_dirty, ...
    'source_unchanged_after_run', ...
        verification_source_after.source_unchanged_after_run, ...
    'rayleigh_global_verifier_sha256', ...
        verification_hashes_before.rayleigh_global, ...
    'affine_residual_verifier_sha256', ...
        verification_hashes_before.affine_residual, ...
    'thin_verifier_sha256',verification_hashes_before.thin);
global_manifest.verification_source.runtime_snapshot_validator_sha256 = ...
    verification_hashes_before.runtime_snapshot;
global_manifest.verification_source.worker_runtime_validator_sha256 = ...
    verification_hashes_before.worker_runtime;
global_manifest.verification_source.persisted_worker_runtime_validator_sha256 = ...
    verification_hashes_before.persisted_worker_runtime;
global_manifest.distribution = local_distribution_record( ...
    expected_atlas_sha256);
global_manifest.validation = struct( ...
    'thin_lossless_interval_replay',true, ...
    'affine_csv_hash_scope_sign_and_cover_rechecked',true, ...
    'affine_interval_execution_is_trusted_evidence',true, ...
    'residual_csv_hash_scope_sign_and_cover_rechecked',true, ...
    'residual_interval_execution_is_trusted_evidence',true, ...
    'spectral_atlas_structure_rechecked',true, ...
    'spectral_atlas_independently_recomputed',true, ...
    'global_replay_runtime_rechecked',true, ...
    'global_replay_all_workers_runtime_rechecked', ...
        spectral.worker_runtime_validation.all_computation_workers_checked, ...
    'component_hashes_rechecked',true);

% Bind the provenance fields to the same verifier bytes that were present
% before any replay began.  This closes the final assembly window as well
% as checking the component artifacts themselves below.
verification_source_final = ver10_assert_source_unchanged( ...
    project_root,verification_source_before);
verification_hashes_after = local_verifier_hashes(project_root);
local_require(isequal(verification_hashes_before, ...
        verification_hashes_after), ...
    'A global-verification program changed during validation.');
global_manifest.verification_source.git_commit = ...
    verification_source_final.git_commit;
global_manifest.verification_source.git_status_available = ...
    verification_source_final.git_status_available;
global_manifest.verification_source.git_dirty = ...
    verification_source_final.git_dirty;
global_manifest.verification_source.source_unchanged_after_run = ...
    verification_source_final.source_unchanged_after_run;

local_require(strcmp(ver10_file_sha256(thin_manifest_path), ...
        snapshot.thin_manifest) ...
    && strcmp(ver10_file_sha256(compact_manifest_path), ...
        snapshot.compact_manifest) ...
    && strcmp(ver10_file_sha256(residual_manifest_path), ...
        snapshot.residual_manifest) ...
    && strcmp(ver10_file_sha256(spectral_atlas_path), ...
        snapshot.spectral_atlas), ...
    'A component manifest or spectral atlas changed during validation.');

if ~isempty(output_path)
    local_write_json(output_path,global_manifest);
end
end


