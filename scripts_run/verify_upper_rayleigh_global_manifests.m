function digest = local_sha256_bytes(bytes)
try
    engine = javaMethod( ...
        'getInstance','java.security.MessageDigest','SHA-256');
catch ME
    error('verify_upper_rayleigh_global_manifests:NoSHA256', ...
        'Cannot initialize SHA-256: %s',ME.message);
end
bytes = uint8(bytes(:));
if ~isempty(bytes)
    engine.update(typecast(bytes,'int8'));
end
raw = typecast(engine.digest(),'uint8');
digest = lower(reshape(dec2hex(raw,2).',1,[]));
end


function local_require(condition,message)
if ~(islogical(condition) || isnumeric(condition)) ...
        || ~isscalar(condition) || ~isfinite(double(condition)) ...
        || ~logical(condition)
    error('verify_upper_rayleigh_global_manifests:InvalidCertificate', ...
        '%s',message);
end
