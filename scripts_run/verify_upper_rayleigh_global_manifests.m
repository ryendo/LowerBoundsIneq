function runtime = local_validate_legacy_runtime(record)
runtime = struct( ...
    'engine',local_text(record,'engine','affine runtime'), ...
    'engine_version',local_text( ...
        record,'engine_version','affine runtime'), ...
    'startintlab_sha256',local_sha256( ...
        record,'startintlab_sha256','affine runtime'), ...
    'intval_constructor_sha256',local_sha256( ...
        record,'intval_constructor_sha256','affine runtime'));
if isfield(record,'intlab_tree_sha256')
    runtime.intlab_tree_sha256 = local_sha256( ...
        record,'intlab_tree_sha256','affine runtime');
else
    runtime.intlab_tree_sha256 = '';
end
runtime.trust_boundary = [ ...
    'The affine v1 artifact predates whole-tree hashing; its clean source ', ...
    'commit, startintlab.m, intval.m, CSV hash, serialized margins, ', ...
    'strict signs, and geometric cover are checked.  The archived INTLAB ', ...
    'execution that produced those serialized margins remains trusted.'];
end


function spectral = local_validate_spectral_atlas( ...
        filename,expected_sha256,expected_commit, ...
        trusted_runtime,trusted_runtime_sha256)
local_require(isfile(filename),'The spectral-atlas MAT file is missing.');
before = ver10_file_sha256(filename);
local_require(strcmp(before,expected_sha256), ...
    'The spectral-atlas MAT hash disagrees with the residual manifest.');
payload = load(filename,'atlas');
after = ver10_file_sha256(filename);
local_require(strcmp(after,expected_sha256), ...
    'The spectral-atlas MAT file changed while it was loaded.');
local_require(isfield(payload,'atlas') ...
    && isstruct(payload.atlas) && isscalar(payload.atlas), ...
    'The spectral-atlas MAT file has no scalar atlas structure.');
value = payload.atlas;
local_require(strcmp(local_text(value,'schema','spectral atlas'), ...
    'lowerboundsineq.omega-up-spectral-cr-lg-atlas.v1'), ...
    'The spectral-atlas schema is unsupported.');
local_require(strcmp(local_text(value,'method','spectral atlas'), ...
    'nearest-anchor-affine-transport-of-LG-Ritz-CR-endpoints'), ...
    'The spectral-atlas method is unsupported.');
local_require(local_flag(value,'rigorous','spectral atlas'), ...
    'The spectral atlas is not rigorous.');
Nx = local_positive_integer(value,'Nx_anchor','spectral atlas');
Ny = local_positive_integer(value,'Ny_anchor','spectral atlas');
num_certificates = local_positive_integer( ...
    value,'num_certificates','spectral atlas');
local_require(Nx == 9 && Ny == 5 && num_certificates == Nx*Ny, ...
    'The spectral atlas is not the canonical 9-by-5 anchor grid.');
local_require(local_positive_integer(value,'N_LG','spectral atlas') == 16 ...
    && local_positive_integer(value,'N_rho','spectral atlas') == 64 ...
    && local_positive_integer(value,'bound_order','spectral atlas') == 2, ...
    'The spectral-atlas discretization is noncanonical.');
local_require(isfield(value,'certificates') ...
    && iscell(value.certificates) ...
    && isequal(size(value.certificates),[Ny,Nx]), ...
    'The spectral-atlas certificate array has the wrong shape.');
local_require(isfield(value,'x_anchors') && isnumeric(value.x_anchors) ...
    && isreal(value.x_anchors) && numel(value.x_anchors) == Nx ...
    && all(isfinite(value.x_anchors(:))) ...
    && all(diff(value.x_anchors(:)) > 0) ...
    && isfield(value,'y_anchors') && isnumeric(value.y_anchors) ...
    && isreal(value.y_anchors) && numel(value.y_anchors) == Ny ...
    && all(isfinite(value.y_anchors(:))) ...
    && all(diff(value.y_anchors(:)) > 0), ...
    'The spectral-atlas anchor vectors are invalid.');
for ix = 1:Nx
    for iy = 1:Ny
        certificate = value.certificates{iy,ix};
        local_validate_anchor_certificate( ...
            certificate,value.x_anchors(ix),value.y_anchors(iy), ...
            value.N_LG,value.N_rho,value.bound_order);
    end
end
[num_replayed,worker_runtime_validation] = local_replay_spectral_atlas( ...
    value,Nx,Ny,trusted_runtime,trusted_runtime_sha256);
source = local_struct(value,'source','spectral atlas');
local_require(strcmp(local_text(source,'git_commit','spectral source'), ...
        expected_commit) ...
    && local_flag(source,'git_status_available','spectral source') ...
    && ~local_flag(source,'git_dirty','spectral source') ...
    && local_flag(source,'source_unchanged_after_run','spectral source'), ...
    'The spectral atlas was not generated from the common clean source.');
spectral_runtime = local_struct(value,'runtime','spectral atlas');
spectral_runtime_sha256 = local_sha256_bytes( ...
    uint8(jsonencode(spectral_runtime)));
local_require(strcmp(local_sha256(value, ...
        'runtime_sha256','spectral atlas'),spectral_runtime_sha256) ...
    && local_flag(value,'runtime_rechecked_after_run','spectral atlas'), ...
    ['The spectral atlas does not bind a full runtime snapshot that was ', ...
     'rechecked after generation.']);
spectral_workers = local_number( ...
    value,'parallel_workers','spectral atlas');
local_require(spectral_workers >= 0 ...
    && spectral_workers == floor(spectral_workers) ...
    && spectral_workers <= 64, ...
    'The spectral-atlas worker count is invalid.');
ver10_validate_worker_runtime_record( ...
    local_struct(value,'worker_runtime_validation','spectral atlas'), ...
    spectral_runtime_sha256,spectral_workers, ...
    'spectral atlas worker runtime validation');

eps_up = I_intval('0.122');
x_left = I_intval('0.5');
x_right = x_left+2*eps_up;
y_top = sqrt(I_intval('3'))/2;
y_bottom = y_top-eps_up;
local_require(local_number(value,'x_domain_lower','spectral atlas') ...
        <= I_inf(x_left) ...
    && I_sup(x_right) <= local_number( ...
        value,'x_domain_upper','spectral atlas') ...
    && local_number(value,'y_domain_lower','spectral atlas') ...
        <= I_inf(y_bottom) ...
    && I_sup(y_top) <= local_number( ...
        value,'y_domain_upper','spectral atlas'), ...
    'The spectral atlas does not cover the canonical residual rectangle.');
spectral = struct( ...
    'num_certificates',num_certificates, ...
    'num_replayed',num_replayed, ...
    'worker_runtime_validation',worker_runtime_validation);
end


function [num_replayed,worker_runtime_validation] = ...
        local_replay_spectral_atlas( ...
            atlas,Nx,Ny,trusted_runtime,trusted_runtime_sha256)
project_root = fileparts(fileparts(mfilename('fullpath')));
workers = local_environment_nonnegative_integer( ...
    'VER10_SPECTRAL_REPLAY_WORKERS',0);
num_replayed = Nx*Ny;
replayed = cell(Ny,Nx);
before_workers = local_serial_worker_report( ...
    trusted_runtime_sha256,'global-spectral-replay-before-dispatch');
after_workers = local_serial_worker_report( ...
    trusted_runtime_sha256,'global-spectral-replay-after-dispatch');
if workers > 0
    pool = ver10_ensure_local_pool(workers);
    initialization = parfevalOnAll( ...
        pool,@omega_up_all_prepare_worker,0,project_root,'interval');
    wait(initialization);
    fetchOutputs(initialization);
    before_workers = ver10_assert_worker_runtime( ...
        pool,trusted_runtime,trusted_runtime_sha256, ...
        'global-spectral-replay-before-dispatch');
    parfor linear_index = 1:num_replayed
        [iy,ix] = ind2sub([Ny,Nx],linear_index);
        triangle = I_intval([ ...
            0,0,1,0,atlas.x_anchors(ix),atlas.y_anchors(iy)]);
        replayed{linear_index} = triangle_spectral_certificate_cr_lg( ...
            triangle,atlas.N_LG,atlas.N_rho,atlas.bound_order,1);
    end
    after_workers = ver10_assert_worker_runtime( ...
        pool,trusted_runtime,trusted_runtime_sha256, ...
        'global-spectral-replay-after-dispatch');
else
    for linear_index = 1:num_replayed
        [iy,ix] = ind2sub([Ny,Nx],linear_index);
        triangle = I_intval([ ...
            0,0,1,0,atlas.x_anchors(ix),atlas.y_anchors(iy)]);
        replayed{linear_index} = triangle_spectral_certificate_cr_lg( ...
            triangle,atlas.N_LG,atlas.N_rho,atlas.bound_order,1);
    end
end
for linear_index = 1:num_replayed
    stored = atlas.certificates{linear_index};
    current = replayed{linear_index};
    local_require(I_inf(stored.lambda_LG_lower) ...
            <= I_inf(current.lambda_LG_lower) ...
        && I_sup(current.lambda_Ritz_upper) ...
            <= I_sup(stored.lambda_Ritz_upper) ...
        && I_inf(stored.lambda_next_CR_lower) ...
            <= I_inf(current.lambda_next_CR_lower), ...
        ['A stored spectral endpoint is not conservative relative to ', ...
         'the independent interval replay.']);
end
worker_runtime_validation = struct( ...
    'policy','full-runtime-json-all-workers-before-and-after-dispatch-v1', ...
    'before_dispatch',before_workers, ...
    'after_dispatch',after_workers, ...
    'all_computation_workers_checked',true, ...
    'runtime_sha256',trusted_runtime_sha256);
end


function value = local_environment_nonnegative_integer(name,default_value)
