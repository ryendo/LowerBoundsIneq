    'repository',repository, ...
    'release_tag',release_tag, ...
    'thin_manifest_repo_path', ...
        'results/paper_certificates/muhat1_rayleigh_t038_v2/manifest.json', ...
    'affine_manifest_repo_path',[ ...
        'results/paper_certificates/upper_affine_atlas/', ...
        'upper_manifest_interval_20260728_162102.json'], ...
    'residual_manifest_repo_path',[ ...
        'results/paper_certificates/omega_up_residual_v2/', ...
        'omega_up_all_manifest.json'], ...
    'global_manifest_repo_path',[ ...
        'results/paper_certificates/', ...
        'siudeja_upper_global_rayleigh_manifest.json'], ...
