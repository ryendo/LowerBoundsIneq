end


function table_value = local_cached_input_table(input_file,input_sha256)
persistent cached_key cached_table
key = [char(input_file),'|',char(input_sha256)];
if isempty(cached_key) || ~strcmp(cached_key,key) || isempty(cached_table)
    hash_before = ver10_file_sha256(input_file);
    if ~strcmp(hash_before,input_sha256)
        error('run_omega_mid_unified_parallel:WorkerInputHashMismatch', ...
            'The worker input CSV does not match the checkpoint fingerprint.');
    end
    cached_table = local_read_input_table(input_file);
    hash_after = ver10_file_sha256(input_file);
    if ~strcmp(hash_after,input_sha256)
        error('run_omega_mid_unified_parallel:WorkerInputChanged', ...
            'The worker input CSV changed while it was being parsed.');
    end
    cached_key = key;
end
table_value = cached_table;
end


function table_value = local_read_input_table(input_file)
% Preserve the exact decimal endpoints written in the CSV.  TextType alone
% does not stop readtable from inferring these four columns as doubles.
import_options = detectImportOptions(input_file,'TextType','string');
endpoint_columns = {'x_inf','x_sup','theta_inf','theta_sup'};
present = endpoint_columns( ...
    ismember(endpoint_columns,import_options.VariableNames));
if numel(present) ~= numel(endpoint_columns)
    error('run_omega_mid_unified_parallel:MissingEndpointColumns', ...
        'The input file is missing an endpoint column.');
end
import_options = setvartype(import_options,present,'string');
table_value = readtable(input_file,import_options);
end


