max_cr_refinement = zeros(n,1);
max_lg_refinement = -ones(n,1);
minimum_cr_mesh = NaN(n,1);
minimum_lg_mesh = NaN(n,1);
evaluated_nodes = zeros(n,1);
spectral_solves = zeros(n,1);
eigenvalue_seconds = NaN(n,1);
cr_shift_seconds = NaN(n,1);
fallback_nodes = zeros(n,1);
analytic_shift_nodes = zeros(n,1);
cr_liu_shift_nodes = zeros(n,1);
direct_cr_nodes = zeros(n,1);
shift_analytic = false(n,1);
shift_cr_liu = false(n,1);
shift_mixed = false(n,1);
shift_not_applicable = false(n,1);
fallback_used = false(n,1);
lg_b_verified_spd = false(n,1);
