    path_value = char(forbidden_absolute_paths{k});
    if ~isempty(path_value) && contains(encoded,path_value)
        error('run_omega_mid_unified_parallel:AbsolutePathInManifest', ...
            'The JSON manifest contains an absolute local path.');
