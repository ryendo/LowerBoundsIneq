function digest = local_sha256_bytes(bytes)
try
    engine = javaMethod( ...
        'getInstance','java.security.MessageDigest','SHA-256');
catch ME
    error('run_omega_mid_unified_parallel:NoSHA256', ...
        'Cannot initialize SHA-256: %s',ME.message);
end
engine.update(typecast(uint8(bytes(:)),'int8'));
raw = typecast(engine.digest(),'uint8');
digest = lower(reshape(dec2hex(raw,2).',1,[]));
end


function state = local_source_state_digest(project_root)
% Bind dirty targeted checkpoints to both normalized Git metadata and the
% SHA-256 content of every tracked change and untracked source file.
old_directory = pwd;
cleanup = onCleanup(@() cd(old_directory));
cd(project_root);

[porcelain_status,porcelain_text] = system( ...
    ['git -c core.quotePath=false status --porcelain=v1 ', ...
     '--untracked-files=normal']);
if porcelain_status ~= 0
    unavailable = local_sha256_utf8('git-source-state-unavailable-v1');
    state = struct( ...
        'available',false, ...
        'normalized_porcelain_sha256',unavailable, ...
        'dirty_content_sha256',unavailable, ...
        'source_state_sha256',unavailable);
    clear cleanup
    return;
end
normalized_porcelain = local_normalize_git_text(porcelain_text);

[tracked_status,tracked_text] = system( ...
    'git -c core.quotePath=false diff --name-only HEAD --');
[untracked_status,untracked_text] = system( ...
    ['git -c core.quotePath=false ls-files --others ', ...
     '--exclude-standard']);
if tracked_status ~= 0 || untracked_status ~= 0
    error('run_omega_mid_unified_parallel:GitDigestFailed', ...
        'Git could not enumerate the dirty worktree content.');
end
paths = [local_git_path_lines(tracked_text); ...
    local_git_path_lines(untracked_text)];
paths = sort(unique(paths));
entries = cell(numel(paths)+1,1);
entries{1} = 'dirty-content-v1';
for k = 1:numel(paths)
    relative = paths{k};
    components = strsplit(strrep(relative,'\','/'),'/');
    if isempty(relative) || local_is_absolute_path(relative) ...
            || any(strcmp(components,'..')) ...
            || any(double(relative) < 32)
        error('run_omega_mid_unified_parallel:UnsupportedGitPath', ...
            'Git reported a path that cannot be fingerprinted safely.');
    end
    absolute = fullfile(project_root,relative);
    if exist(absolute,'file') == 2
        info = dir(absolute);
        entries{k+1} = sprintf( ...
            'file\t%s\t%.0f\t%s',relative,info.bytes, ...
            ver10_file_sha256(absolute));
    elseif exist(absolute,'dir') == 7
        error('run_omega_mid_unified_parallel:UnsupportedGitPath', ...
            ['A changed Git path is a directory or submodule and ', ...
             'cannot be content-fingerprinted by this driver.']);
    else
        entries{k+1} = sprintf('missing\t%s',relative);
    end
end
dirty_payload = strjoin(entries,sprintf('\n'));
porcelain_sha256 = local_sha256_utf8(normalized_porcelain);
dirty_content_sha256 = local_sha256_utf8(dirty_payload);
state_payload = sprintf( ...
    'source-state-v1|porcelain=%s|dirty-content=%s', ...
    porcelain_sha256,dirty_content_sha256);
state = struct( ...
    'available',true, ...
    'normalized_porcelain_sha256',porcelain_sha256, ...
    'dirty_content_sha256',dirty_content_sha256, ...
    'source_state_sha256',local_sha256_utf8(state_payload));
clear cleanup
end


function lines = local_git_path_lines(text)
normalized = local_normalize_git_text(text);
if isempty(normalized)
    lines = cell(0,1);
    return;
end
lines = regexp(normalized,sprintf('\n'),'split').';
if any(cellfun(@isempty,lines))
    error('run_omega_mid_unified_parallel:UnsupportedGitPath', ...
        'Git returned an empty path while constructing the source digest.');
end
end


function normalized = local_normalize_git_text(text)
normalized = strrep(char(text),sprintf('\r\n'),sprintf('\n'));
normalized = strrep(normalized,sprintf('\r'),sprintf('\n'));
while ~isempty(normalized) && normalized(end) == sprintf('\n')
    normalized(end) = [];
end
end


function digest = local_sha256_utf8(text)
try
    bytes = unicode2native(char(text),'UTF-8');
catch
    bytes = uint8(char(text));
end
digest = local_sha256_bytes(uint8(bytes));
end


