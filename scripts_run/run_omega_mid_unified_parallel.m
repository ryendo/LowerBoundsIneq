end


function chunks = local_build_chunks( ...
    selected_rows,selected_ids,chunk_size,checkpoint_dir)
n = numel(selected_rows);
nchunks = ceil(n/chunk_size);
template = struct( ...
    'ordinal',0, ...
    'selected_offset',0, ...
    'count',0, ...
    'row_indices',[], ...
    'expected_cell_ids',[], ...
    'checkpoint','');
chunks = repmat(template,nchunks,1);
for q = 1:nchunks
    first = (q-1)*chunk_size+1;
    last = min(q*chunk_size,n);
    rows = selected_rows(first:last);
    ids = selected_ids(first:last);
    chunks(q).ordinal = q;
    chunks(q).selected_offset = first;
    chunks(q).count = numel(rows);
    chunks(q).row_indices = rows(:);
    chunks(q).expected_cell_ids = ids(:);
    chunks(q).checkpoint = fullfile(checkpoint_dir,sprintf( ...
        'chunk_%06d_rows_%06d_%06d.mat', ...
        q,min(rows),max(rows)));
end
end


function [selected_rows,selection] = local_select_rows( ...
    input_ids,requested_ids,input_ids_sha256)
if isempty(requested_ids)
    selected_rows = (1:numel(input_ids)).';
    mode = 'all-input-rows';
    manifest_cell_ids = [];
    selected_ids_sha256 = input_ids_sha256;
else
    requested_ids = double(requested_ids(:));
    if numel(unique(requested_ids)) ~= numel(requested_ids)
        error('run_omega_mid_unified_parallel:DuplicateRequestedIds', ...
            'cell_ids must not contain duplicates.');
    end
    [found,locations] = ismember(requested_ids,input_ids);
    if ~all(found)
        missing = requested_ids(~found);
        error('run_omega_mid_unified_parallel:UnknownCellIds', ...
            'Unknown cell id(s), beginning with %.17g.',missing(1));
    end
    selected_rows = sort(locations(:));
    mode = 'explicit-cell-ids';
    manifest_cell_ids = sort(requested_ids(:)).';
    selected_ids_sha256 = local_ids_sha256( ...
        input_ids(selected_rows));
end
selection = struct( ...
    'mode',mode, ...
    'selected_ids_sha256',selected_ids_sha256, ...
    'manifest_cell_ids',manifest_cell_ids);
end


function [ids,validation] = local_validate_input(input_table,input_file)
required = {'i','x_inf','x_sup','theta_inf','theta_sup', ...
    'mesh_size_lower_cr','isLG','mesh_size_lower_LG', ...
    'fem_order_lower_LG'};
variables = input_table.Properties.VariableNames;
missing = required(~ismember(required,variables));
if ~isempty(missing)
    error('run_omega_mid_unified_parallel:MissingInputColumns', ...
        'Missing column %s in %s.',missing{1},input_file);
end
if height(input_table) == 0
    error('run_omega_mid_unified_parallel:EmptyInput', ...
        'The cell definition file is empty.');
end

ids = local_column_numbers(input_table.i);
if any(~isfinite(ids)) || any(ids ~= floor(ids)) || any(ids < 1)
    error('run_omega_mid_unified_parallel:BadCellIds', ...
        'Every input cell id must be a finite positive integer.');
end
if numel(unique(ids)) ~= numel(ids)
    error('run_omega_mid_unified_parallel:DuplicateInputIds', ...
        'The input cell ids are not unique.');
end

x_lo = local_column_numbers(input_table.x_inf);
x_hi = local_column_numbers(input_table.x_sup);
t_lo = local_column_numbers(input_table.theta_inf);
t_hi = local_column_numbers(input_table.theta_sup);
h_cr = local_column_numbers(input_table.mesh_size_lower_cr);
is_lg = local_column_numbers(input_table.isLG);
h_lg = local_column_numbers(input_table.mesh_size_lower_LG);
order_lg = local_column_numbers(input_table.fem_order_lower_LG);
all_geometry = [x_lo;x_hi;t_lo;t_hi;h_cr;is_lg;h_lg;order_lg];
if any(~isfinite(all_geometry))
    error('run_omega_mid_unified_parallel:NonfiniteInput', ...
        'The input contains a nonfinite numerical field.');
end
if any(x_hi < x_lo) || any(t_hi < t_lo) ...
        || any(h_cr <= 0) || any(h_lg <= 0) ...
        || any(~ismember(is_lg,[0,1])) ...
        || any(order_lg < 1) || any(order_lg ~= floor(order_lg))
    error('run_omega_mid_unified_parallel:InvalidInputGeometry', ...
        'The cell definition contains an invalid interval or FEM parameter.');
end

validation = struct();
validation.required_columns_present = true;
validation.cell_ids_unique = true;
validation.numeric_fields_finite = true;
validation.intervals_ordered = true;
validation.mesh_parameters_valid = true;
validation.minimum_cell_id = min(ids);
validation.maximum_cell_id = max(ids);
validation.ids_equal_row_numbers = isequal(ids(:),(1:numel(ids)).');
end


function summary = local_summarize( ...
