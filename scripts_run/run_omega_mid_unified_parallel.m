function [methods,cr_levels,lg_levels] = local_fem_attempt_schedule( ...
    cell_data,depth,max_depth,fem_policy)
cr_available = local_available_refinement_levels( ...
    local_num_value(cell_data.mesh_size_lower_cr), ...
    fem_policy.minimum_cr_mesh_size, ...
    fem_policy.max_refinement_level);
lg_available = local_available_refinement_levels( ...
    local_num_value(cell_data.mesh_size_lower_LG), ...
    fem_policy.minimum_lg_mesh_size, ...
    fem_policy.max_refinement_level);
is_lg_requested = logical(local_num_value(cell_data.isLG));

methods = {};
cr_levels = zeros(0,1);
lg_levels = zeros(0,1);
if is_lg_requested
    for k = 1:numel(lg_available)
        methods{end+1,1} = 'LG'; %#ok<AGROW>
        cr_levels(end+1,1) = cr_available( ...
            min(k,numel(cr_available))); %#ok<AGROW>
        lg_levels(end+1,1) = lg_available(k); %#ok<AGROW>
    end
else
    for k = 1:numel(cr_available)
        methods{end+1,1} = 'CR'; %#ok<AGROW>
        cr_levels(end+1,1) = cr_available(k); %#ok<AGROW>
        lg_levels(end+1,1) = -1; %#ok<AGROW>
    end
    % Geometric overestimation should be reduced before paying for LG.
    % Only a terminal geometric leaf may use the LG fallback schedule.
    if depth >= max_depth
        terminal_cr_level = cr_available(end);
        for k = 1:numel(lg_available)
            methods{end+1,1} = 'LG'; %#ok<AGROW>
            cr_levels(end+1,1) = terminal_cr_level; %#ok<AGROW>
            lg_levels(end+1,1) = lg_available(k); %#ok<AGROW>
        end
    end
end
end


function levels = local_available_refinement_levels( ...
    base_size,minimum_size,max_level)
if ~isfinite(base_size) || base_size <= 0
    error('run_omega_mid_unified_parallel:BadBaseMeshSize', ...
        'Every FEM mesh size must be finite and positive.');
end
effective_minimum = min(base_size,minimum_size);
levels = 0;
previous = base_size;
for level = 1:max_level
    current = local_refined_mesh_size( ...
        base_size,level,effective_minimum);
    if current == previous
        break;
    end
    levels(end+1,1) = level; %#ok<AGROW>
    previous = current;
end
levels = levels(:);
end


function mesh_size = local_refined_mesh_size( ...
    base_size,level,minimum_size)
effective_minimum = min(base_size,minimum_size);
mesh_size = max(base_size/(2^level),effective_minimum);
end


