function leaf = local_evaluate_leaf( ...
    cell_data,path,depth,max_depth,fem_policy, ...
    rigorous,allow_lg_escalation)
leaf = local_blank_leaf();
leaf.path = path;
leaf.depth = depth;
[leaf.x_inf,leaf.x_sup,leaf.theta_inf,leaf.theta_sup] = ...
    local_cell_enclosure(cell_data);
leaf.isLG_requested = logical(local_num_value(cell_data.isLG));
leaf.base_mesh_size_cr = local_num_value( ...
    cell_data.mesh_size_lower_cr);
leaf.base_mesh_size_lg = local_num_value( ...
    cell_data.mesh_size_lower_LG);
leaf.fem_order_lg = local_num_value( ...
    cell_data.fem_order_lower_LG);
leaf.LG_escalation_allowed = logical(allow_lg_escalation);
leaf.rigorous = logical(rigorous);
started = tic;

[method_schedule,cr_levels,lg_levels] = local_fem_attempt_schedule( ...
    cell_data,depth,max_depth,fem_policy);
attempts = repmat(local_blank_attempt(),0,1);
selected = 0;
for q = 1:numel(method_schedule)
    attempt_data = cell_data;
    attempt_data.mesh_size_lower_cr = local_refined_mesh_size( ...
        local_num_value(cell_data.mesh_size_lower_cr), ...
        cr_levels(q),fem_policy.minimum_cr_mesh_size);
    attempt_data.mesh_size_lower_LG = local_refined_mesh_size( ...
        local_num_value(cell_data.mesh_size_lower_LG), ...
        max(lg_levels(q),0),fem_policy.minimum_lg_mesh_size);
    attempt_data.isLG = strcmp(method_schedule{q},'LG');
    attempt_data.allow_lg_escalation = false;
    attempt = local_evaluate_fem_attempt( ...
        attempt_data,q,method_schedule{q}, ...
        cr_levels(q),lg_levels(q),rigorous);
    attempts(end+1,1) = attempt; %#ok<AGROW>
    selected = q;
    if attempt.strict_checks_passed
        break;
    end
end
if isempty(attempts)
    error('run_omega_mid_unified_parallel:NoFEMAttempts', ...
        'The deterministic FEM refinement schedule is empty.');
end

leaf = local_apply_attempt_to_leaf(leaf,attempts(selected));
leaf.attempts = attempts;
leaf.selected_attempt_ordinal = selected;
leaf.first_strict_attempt_ordinal = find( ...
    [attempts.strict_checks_passed],1);
if isempty(leaf.first_strict_attempt_ordinal)
    leaf.first_strict_attempt_ordinal = 0;
end
leaf.eigenvalue_attempts = numel(attempts);
leaf.escalated = ~leaf.isLG_requested ...
    && strcmp(leaf.method,'LG');
leaf.eigenvalue_total_seconds = sum( ...
    [attempts.eigenvalue_total_seconds]);
leaf.LG_CR_shift_seconds = sum([attempts.LG_CR_shift_seconds]);
leaf.elapsed_seconds = toc(started);
leaf.completed = true;
end


function attempt = local_evaluate_fem_attempt( ...
    cell_data,ordinal,method,cr_level,lg_level,rigorous)
attempt = local_blank_attempt();
attempt.ordinal = ordinal;
attempt.method = method;
attempt.cr_refinement_level = cr_level;
attempt.lg_refinement_level = lg_level;
attempt.mesh_size_cr = local_num_value( ...
    cell_data.mesh_size_lower_cr);
attempt.mesh_size_lg = local_num_value( ...
    cell_data.mesh_size_lower_LG);
attempt.rigorous = logical(rigorous);
started = tic;
try
    [verified,J_lower,diagnostics] = ...
        verify_J_both_positive(cell_data);
    if ~strcmp(char(diagnostics.method_used),method)
        error('run_omega_mid_unified_parallel:FEMMethodMismatch', ...
            'The FEM attempt returned a different spectral method.');
    end
    attempt.computed = true;
    attempt.lambda1_lower = local_finite_or_nan( ...
        local_lower_scalar(diagnostics.lambda1_lower));
    attempt.J1_lower = local_finite_or_nan( ...
        local_lower_scalar(J_lower.J1));
    attempt.J2_lower = local_finite_or_nan( ...
        local_lower_scalar(J_lower.J2));
    attempt.conditions_verified = logical(local_field( ...
        diagnostics.eigenvalue,'conditions_verified',false));
    attempt.LG_shift_method = local_text_value(local_field( ...
        diagnostics.eigenvalue,'shift_method','not-recorded'));
    attempt.LG_fallback_used = logical(local_field( ...
        diagnostics.eigenvalue,'fallback_used',false));
    attempt.LG_fallback_reason = local_text_value(local_field( ...
        diagnostics.eigenvalue,'fallback_reason',''));
    timing = local_field(diagnostics.eigenvalue,'timing',struct());
    attempt.eigenvalue_total_seconds = local_nonnegative_or_nan( ...
        local_field(timing,'total_seconds',NaN));
    attempt.LG_CR_shift_seconds = local_nonnegative_or_nan( ...
        local_field(timing,'cr_shift_seconds',0));
    attempt.LG_B_verified_spd = logical(local_field( ...
        diagnostics.eigenvalue,'B_verified_spd', ...
        strcmp(method,'CR')));

    if strcmp(method,'LG')
        attempt.LG_rho_lower = local_finite_or_nan( ...
            local_lower_scalar(local_field( ...
                diagnostics.eigenvalue,'rho',NaN)));
        attempt.LG_ritz_upper = local_finite_or_nan( ...
            local_upper_scalar(local_field( ...
                diagnostics.eigenvalue,'verified_ritz_upper',NaN)));
        attempt.LG_separation_margin_lower = local_finite_or_nan( ...
            local_lower_scalar(local_field( ...
                diagnostics.eigenvalue,'separation_margin',NaN)));
        attempt.LG_mu_upper = local_finite_or_nan( ...
            local_upper_scalar(local_field( ...
                diagnostics.eigenvalue,'mu_upper',NaN)));
        spectral_checks = attempt.conditions_verified ...
            && attempt.LG_B_verified_spd ...
            && isfinite(attempt.LG_rho_lower) ...
            && attempt.LG_rho_lower > 0 ...
            && isfinite(attempt.LG_ritz_upper) ...
            && attempt.LG_ritz_upper > 0 ...
            && attempt.LG_rho_lower > attempt.LG_ritz_upper ...
            && isfinite(attempt.LG_separation_margin_lower) ...
            && attempt.LG_separation_margin_lower > 0 ...
            && isfinite(attempt.LG_mu_upper) ...
            && attempt.LG_mu_upper < 0;
    else
        spectral_checks = attempt.conditions_verified;
    end

    attempt.J1_positive = logical(diagnostics.verified_J1) ...
        && isfinite(attempt.J1_lower) && attempt.J1_lower > 0;
    attempt.J2_positive = logical(diagnostics.verified_J2) ...
        && isfinite(attempt.J2_lower) && attempt.J2_lower > 0;
    attempt.strict_checks_passed = logical(verified) ...
        && attempt.J1_positive && attempt.J2_positive ...
        && isfinite(attempt.lambda1_lower) ...
        && attempt.lambda1_lower > 0 && spectral_checks;
    attempt.J1_certified = logical(rigorous) ...
        && attempt.strict_checks_passed;
    attempt.J2_certified = logical(rigorous) ...
        && attempt.strict_checks_passed;
    attempt.all_certified = ...
        attempt.J1_certified && attempt.J2_certified;
    if attempt.strict_checks_passed
        if rigorous
            attempt.status = 'ok';
            attempt.certificate_status = 'certified_interval';
        else
            attempt.status = 'exploratory_positive';
            attempt.certificate_status = 'exploratory_double';
        end
    else
        attempt.status = 'invalid_result';
        attempt.certificate_status = 'invalid';
        attempt.error_identifier = ...
            'run_omega_mid_unified_parallel:FEMAttemptStrictChecksFailed';
        attempt.error_message = ...
            'The FEM attempt did not pass strict proof checks.';
    end
catch ME
    attempt.computed = false;
    attempt.status = 'error';
    attempt.certificate_status = 'error';
    attempt.error_identifier = local_nonempty_error_identifier(ME);
    attempt.error_message = ME.message;
end
attempt.elapsed_seconds = toc(started);
if ~isfinite(attempt.eigenvalue_total_seconds)
    attempt.eigenvalue_total_seconds = attempt.elapsed_seconds;
end
if ~isfinite(attempt.LG_CR_shift_seconds)
    attempt.LG_CR_shift_seconds = 0;
end
attempt.completed = true;
end


function leaf = local_apply_attempt_to_leaf(leaf,attempt)
fields = {'computed','method','conditions_verified','lambda1_lower', ...
    'LG_shift_method','LG_fallback_used','LG_fallback_reason', ...
    'LG_B_verified_spd','LG_rho_lower','LG_ritz_upper', ...
    'LG_separation_margin_lower','LG_mu_upper','J1_lower','J2_lower', ...
    'J1_positive','J2_positive','strict_checks_passed', ...
    'J1_certified','J2_certified','all_certified','status', ...
    'certificate_status','error_identifier','error_message'};
for k = 1:numel(fields)
    name = fields{k};
    leaf.(name) = attempt.(name);
end
leaf.cr_refinement_level = attempt.cr_refinement_level;
leaf.lg_refinement_level = attempt.lg_refinement_level;
leaf.mesh_size_cr_used = attempt.mesh_size_cr;
leaf.mesh_size_lg_used = attempt.mesh_size_lg;
end


function record = local_aggregate_parent_record( ...
    record,leaves,statistics,rigorous)
record.leaves = leaves;
record.leaf_count = numel(leaves);
if isempty(leaves)
    error('run_omega_mid_unified_parallel:NoSubdivisionLeaves', ...
        'Adaptive certification returned no leaves.');
end
depths = [leaves.depth];
record.max_leaf_depth = max(depths);
record.subdivision_used = any(depths > 0);
record.fem_refinement_used = ...
    any([leaves.cr_refinement_level] > 0) ...
    || any([leaves.lg_refinement_level] > 0);
record.max_cr_refinement_level_used = ...
    max([leaves.cr_refinement_level]);
record.max_lg_refinement_level_used = ...
    max([leaves.lg_refinement_level]);
record.minimum_cr_mesh_size_used = ...
    min([leaves.mesh_size_cr_used]);
lg_selected = strcmp({leaves.method},'LG');
if any(lg_selected)
    record.minimum_lg_mesh_size_used = ...
        min([leaves(lg_selected).mesh_size_lg_used]);
else
    record.minimum_lg_mesh_size_used = NaN;
end
record.evaluated_node_count = statistics.evaluated_node_count;
record.spectral_solve_count = statistics.spectral_solve_count;
record.eigenvalue_total_seconds = ...
    statistics.eigenvalue_total_seconds;
record.LG_CR_shift_seconds = statistics.LG_CR_shift_seconds;
record.LG_fallback_node_count = ...
    statistics.LG_fallback_node_count;
record.LG_analytic_shift_node_count = ...
    statistics.LG_analytic_shift_node_count;
record.LG_CR_Liu_shift_node_count = ...
    statistics.LG_CR_Liu_shift_node_count;
record.direct_CR_node_count = statistics.direct_CR_node_count;
record.LG_shift_method = local_aggregate_shift_method(statistics);
record.LG_fallback_used = statistics.LG_fallback_node_count > 0;
record.LG_fallback_reason = local_join_unique_text( ...
    statistics.LG_fallback_reasons);
record.eigenvalue_attempts = statistics.spectral_solve_count;
record.escalated = any([leaves.escalated]);
record.conditions_verified = all([leaves.conditions_verified]);
record.computed = all([leaves.completed]);

leaf_valid = false(numel(leaves),1);
for k = 1:numel(leaves)
    leaf_valid(k) = local_leaf_has_valid_result(leaves(k),rigorous);
end
all_valid = all(leaf_valid);
if record.leaf_count == 1 && ~record.subdivision_used
    record.method = leaves(1).method;
else
    record.method = 'SUBDIVISION';
end

if all_valid
    record.lambda1_lower = min([leaves.lambda1_lower]);
    record.J1_lower = min([leaves.J1_lower]);
    record.J2_lower = min([leaves.J2_lower]);
    lg = strcmp({leaves.method},'LG');
    if any(lg)
        record.LG_B_verified_spd = ...
            all([leaves(lg).LG_B_verified_spd]);
        record.LG_rho_lower = min([leaves(lg).LG_rho_lower]);
        record.LG_ritz_upper = max([leaves(lg).LG_ritz_upper]);
        record.LG_separation_margin_lower = ...
            min([leaves(lg).LG_separation_margin_lower]);
        record.LG_mu_upper = max([leaves(lg).LG_mu_upper]);
    end
else
    record.lambda1_lower = NaN;
    record.J1_lower = NaN;
    record.J2_lower = NaN;
end

record.J1_positive = all_valid ...
    && isfinite(record.J1_lower) && record.J1_lower > 0;
record.J2_positive = all_valid ...
    && isfinite(record.J2_lower) && record.J2_lower > 0;
record.strict_checks_passed = all_valid ...
    && record.J1_positive && record.J2_positive;
record.J1_certified = logical(rigorous) ...
    && record.strict_checks_passed;
record.J2_certified = logical(rigorous) ...
    && record.strict_checks_passed;
record.all_certified = record.J1_certified && record.J2_certified;

if record.strict_checks_passed
    if rigorous
        record.status = 'ok';
        record.certificate_status = 'certified_interval';
    else
        record.status = 'exploratory_positive';
        record.certificate_status = 'exploratory_double';
    end
    if record.subdivision_used
        record.note = sprintf( ...
            ['derived from subdivision: leaves=%d, max_depth=%d, ', ...
             'max_CR_refinement=%d, max_LG_refinement=%d'], ...
            record.leaf_count,record.max_leaf_depth, ...
            record.max_cr_refinement_level_used, ...
            record.max_lg_refinement_level_used);
    elseif record.fem_refinement_used
        record.note = sprintf( ...
            'derived after deterministic FEM refinement: CR=%d, LG=%d', ...
            record.max_cr_refinement_level_used, ...
            record.max_lg_refinement_level_used);
    end
else
    record.status = 'invalid_result';
    record.certificate_status = 'invalid';
    record.error_identifier = ...
        'run_omega_mid_unified_parallel:SubdivisionIncomplete';
    failed_leaves = leaves(~leaf_valid);
    details = cell(min(8,numel(failed_leaves)),1);
    for k = 1:numel(details)
        failed = failed_leaves(k);
        details{k} = sprintf( ...
            ['path=%s method=%s J1=%.17g J2=%.17g ', ...
             'hCR=%.17g hLG=%.17g rCR=%d rLG=%d error=%s'], ...
            failed.path,failed.method,failed.J1_lower,failed.J2_lower, ...
            failed.mesh_size_cr_used,failed.mesh_size_lg_used, ...
            failed.cr_refinement_level,failed.lg_refinement_level, ...
            failed.error_identifier);
    end
    record.error_message = sprintf( ...
        'Uncertified terminal leaf diagnostics: %s.', ...
        strjoin(details,'; '));
end
end


function children = local_split_cell(cell_data)
x_lo_I = I_intval(cell_data.x_inf);
x_hi_I = I_intval(cell_data.x_sup);
t_lo_I = I_intval(cell_data.theta_inf);
t_hi_I = I_intval(cell_data.theta_sup);
x_mid_I = (x_lo_I+x_hi_I)/2;
t_mid_I = (t_lo_I+t_hi_I)/2;
x_lo = I_inf(x_lo_I);
x_hi = I_sup(x_hi_I);
t_lo = I_inf(t_lo_I);
t_hi = I_sup(t_hi_I);
x_mid_lo = I_inf(x_mid_I);
x_mid_hi = I_sup(x_mid_I);
t_mid_lo = I_inf(t_mid_I);
t_mid_hi = I_sup(t_mid_I);
if ~(x_lo < x_mid_lo && x_mid_hi < x_hi ...
        && t_lo < t_mid_lo && t_mid_hi < t_hi)
    error('run_omega_mid_unified_parallel:SubdivisionStagnated', ...
        'An interval midpoint no longer strictly refines its parent.');
end

children = repmat(cell_data,4,1);
% Deterministic order: lower-left, lower-right, upper-left, upper-right.
children(1).x_inf = x_lo;
children(1).x_sup = x_mid_hi;
children(1).theta_inf = t_lo;
children(1).theta_sup = t_mid_hi;
children(2).x_inf = x_mid_lo;
children(2).x_sup = x_hi;
children(2).theta_inf = t_lo;
children(2).theta_sup = t_mid_hi;
children(3).x_inf = x_lo;
children(3).x_sup = x_mid_hi;
children(3).theta_inf = t_mid_lo;
children(3).theta_sup = t_hi;
children(4).x_inf = x_mid_lo;
children(4).x_sup = x_hi;
children(4).theta_inf = t_mid_lo;
children(4).theta_sup = t_hi;
end


