    max(max_cr_refinement);
summary.maximum_LG_refinement_level_used = ...
    max(max_lg_refinement);
summary.minimum_CR_mesh_size_used = ...
    local_finite_min(minimum_cr_mesh);
summary.minimum_LG_mesh_size_used = ...
    local_finite_min(minimum_lg_mesh);
summary.total_evaluated_nodes = sum(evaluated_nodes);
summary.total_spectral_solves = sum(spectral_solves);
summary.total_FEM_attempts = sum(spectral_solves);
summary.LG_shift_counts = struct( ...
    'analytic_parent_records',sum(shift_analytic), ...
    'CR_Liu_parent_records',sum(shift_cr_liu), ...
    'mixed_parent_records',sum(shift_mixed), ...
    'not_applicable_parent_records',sum(shift_not_applicable), ...
    'fallback_parent_records',sum(fallback_used), ...
    'analytic_evaluated_nodes',sum(analytic_shift_nodes), ...
    'CR_Liu_evaluated_nodes',sum(cr_liu_shift_nodes), ...
    'fallback_evaluated_nodes',sum(fallback_nodes), ...
    'direct_CR_evaluated_nodes',sum(direct_cr_nodes));
summary.total_eigenvalue_seconds = ...
    sum(eigenvalue_seconds(isfinite(eigenvalue_seconds)));
summary.total_LG_CR_shift_seconds = ...
    sum(cr_shift_seconds(isfinite(cr_shift_seconds)));
summary.num_records_with_verified_LG_B_SPD = ...
    sum(lg_b_verified_spd);
summary.minimum_J1_lower = local_finite_min(j1(strict));
summary.minimum_J2_lower = local_finite_min(j2(strict));
summary.minimum_lambda1_lower = local_finite_min(lambda(strict));
summary.minimum_LG_separation_margin = ...
    local_finite_min(separation(strict & isfinite(separation)));
summary.maximum_LG_mu_upper = ...
    local_finite_max(mu_upper(strict & isfinite(mu_upper)));
summary.minimum_LG_rho_lower = ...
    local_finite_min(rho_lower(strict & isfinite(rho_lower)));
summary.maximum_LG_ritz_upper = ...
    local_finite_max(ritz_upper(strict & isfinite(ritz_upper)));
summary.wall_seconds = wall_seconds;
summary.sum_cell_seconds = sum(elapsed(isfinite(elapsed)));
summary.num_resumed_records = num_resumed_records;
summary.num_computed_this_invocation = computed_this_invocation;
summary.complete_certificate = logical(rigorous) ...
    && summary.source_clean ...
    && exact_full ...
    && n > 0 ...
    && all(strict) ...
    && all(cert1) ...
    && all(cert2) ...
    && ~any(errors) ...
    && ~any(invalid) ...
    && all(isfinite(j1) & j1 > 0) ...
    && all(isfinite(j2) & j2 > 0) ...
    && all(isfinite(lambda) & lambda > 0);
end


