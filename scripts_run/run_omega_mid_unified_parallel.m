function manifest = run_omega_mid_unified_parallel(varargin)
%RUN_OMEGA_MID_UNIFIED_PARALLEL  Rigorous, resumable Omega_mid certificate.
%
% This driver evaluates J1 and J2 together.  At every evaluated parent or
% leaf node it calls verify_J_both_positive exactly once, so the common
% CR/Liu or Liu--Lehmann--Goerisch eigenvalue computation is reused by both
% functionals.  Rows assigned to CR use dyadically refined CR meshes on
% every quadtree node; failed nodes are refined geometrically, with LG
% attempted only at the terminal geometric depth.  Rows explicitly
% assigned to LG retain the Liu--LG path.
%
% Production example:
%   run_omega_mid_unified_parallel( ...
%       'mode','interval','workers',20, ...
%       'input_file','inputs/cell_def.csv', ...
%       'chunk_size',256, ...
%       'run_name','ver10_omega_mid_unified_prod');
%
% Resume model:
%   The selected input rows are divided into deterministic chunks.  Every
%   worker owns a distinct chunk checkpoint, and publishes an atomic MAT
%   replacement after each configured batch of cells.  A killed job
%   therefore loses at most checkpoint_every-1 completed cell evaluations
%   in each active chunk.  The final CSVs and manifest are rebuilt
%   deterministically from the checkpoints.

project_root = fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(project_root,'scripts_run'));
source = ver10_source_provenance(project_root);
source_state = local_source_state_digest(project_root);
source.normalized_porcelain_sha256 = ...
    source_state.normalized_porcelain_sha256;
source.dirty_content_sha256 = source_state.dirty_content_sha256;
source.source_state_sha256 = source_state.source_state_sha256;
source.source_state_digest_captured_before_run = true;

p = inputParser;
p.CaseSensitive = true;
if isprop(p,'PartialMatching')
    p.PartialMatching = false;
end
addParameter(p,'mode','interval',@(x) ischar(x) || isstring(x));
addParameter(p,'workers',20,@local_nonnegative_integer);
addParameter(p,'input_file',fullfile(project_root,'inputs','cell_def.csv'), ...
    @(x) ischar(x) || isstring(x));
addParameter(p,'output_dir', ...
    fullfile(project_root,'results','omega_mid_unified'), ...
    @(x) ischar(x) || isstring(x));
addParameter(p,'run_name','',@(x) ischar(x) || isstring(x));
addParameter(p,'chunk_size',256,@local_positive_integer);
addParameter(p,'checkpoint_every',32,@local_positive_integer);
addParameter(p,'max_subdivision_depth',8,@local_nonnegative_integer);
addParameter(p,'max_fem_refinement_level',2,@local_nonnegative_integer);
addParameter(p,'minimum_cr_mesh_size',0.005,@local_positive_scalar);
addParameter(p,'minimum_lg_mesh_size',0.025,@local_positive_scalar);
addParameter(p,'resume',true,@(x) islogical(x) || isnumeric(x));
addParameter(p,'retry_failed',true,@(x) islogical(x) || isnumeric(x));
addParameter(p,'cell_ids',[],@local_optional_cell_ids);
parse(p,varargin{:});
opt = p.Results;
fem_policy = struct( ...
    'max_refinement_level',double(opt.max_fem_refinement_level), ...
    'minimum_cr_mesh_size',double(opt.minimum_cr_mesh_size), ...
    'minimum_lg_mesh_size',double(opt.minimum_lg_mesh_size), ...
    'scheme','dyadic-CR-then-terminal-LG-v1');
lg_escalation_policy = ...
    'LG-input-or-terminal-depth-after-CR-refinement-v1';
leaf_acceptance_policy = 'strict-CR-or-LG-J1-and-J2-v1';
unverified_leaf_policy = 'fail-closed-parent-invalid-v1';

mode = lower(char(opt.mode));
if ~any(strcmp(mode,{'interval','double'}))
    error('run_omega_mid_unified_parallel:BadMode', ...
        'mode must be ''interval'' or ''double''.');
end
rigorous = strcmp(mode,'interval');
input_file = local_resolve_file(project_root,char(opt.input_file));
input_sha256 = ver10_file_sha256(input_file);
input_table = local_read_input_table(input_file);
[input_ids,input_validation] = local_validate_input(input_table,input_file);
input_count = numel(input_ids);
input_ids_sha256 = local_ids_sha256(input_ids);

[selected_rows,selection] = local_select_rows( ...
    input_ids,opt.cell_ids,input_ids_sha256);
selected_ids = input_ids(selected_rows);
selected_count = numel(selected_rows);
full_input_coverage = selected_count == input_count ...
    && isequal(sort(selected_ids(:)),sort(input_ids(:)));

if rigorous && full_input_coverage
    if ~source.git_status_available || source.git_dirty ...
            || isempty(source.git_commit)
        error('run_omega_mid_unified_parallel:DirtyProductionTree', ...
            ['A complete interval certificate requires a clean Git ', ...
             'checkout with a resolved commit.  Commit the source before ', ...
             'starting the production run.']);
    end
end

config = struct();
config.schema = 'lowerboundsineq.omega_mid_unified.config.v1';
config.implementation = ...
    ['shared-CR-Liu-LG-J1-J2-adaptive-quadtree-', ...
     'dyadic-FEM-shift-diagnostics-v10'];
config.mode = mode;
config.rigorous = rigorous;
config.input_file = ver10_portable_path(project_root,input_file);
config.input_sha256 = input_sha256;
config.input_cell_count = input_count;
config.input_ids_sha256 = input_ids_sha256;
config.selected_cell_count = selected_count;
config.selected_ids_sha256 = selection.selected_ids_sha256;
config.selection_mode = selection.mode;
config.chunk_size = double(opt.chunk_size);
config.max_subdivision_depth = double(opt.max_subdivision_depth);
config.max_fem_refinement_level = fem_policy.max_refinement_level;
config.minimum_cr_mesh_size = fem_policy.minimum_cr_mesh_size;
config.minimum_lg_mesh_size = fem_policy.minimum_lg_mesh_size;
config.fem_refinement_scheme = fem_policy.scheme;
config.LG_escalation_policy = lg_escalation_policy;
config.leaf_acceptance_policy = leaf_acceptance_policy;
config.unverified_leaf_policy = unverified_leaf_policy;
config.source_git_commit = source.git_commit;
config.source_git_clean = source.git_status_available && ~source.git_dirty;
config.source_normalized_porcelain_sha256 = ...
    source.normalized_porcelain_sha256;
config.source_dirty_content_sha256 = source.dirty_content_sha256;
config.source_state_sha256 = source.source_state_sha256;
config.full_input_coverage = full_input_coverage;
fingerprint_payload = sprintf([ ...
    'schema=%s|implementation=%s|mode=%s|input=%s|input_ids=%s|', ...
    'selected_ids=%s|selected_count=%d|chunk_size=%d|maxdepth=%d|', ...
    'maxfem=%d|mincr=%.17g|minlg=%.17g|femscheme=%s|', ...
    'lgpolicy=%s|accept=%s|unverified=%s|', ...
    'git=%s|clean=%d|porcelain=%s|dirtycontent=%s|', ...
    'sourcestate=%s'], ...
    config.schema,config.implementation,config.mode, ...
    config.input_sha256,config.input_ids_sha256, ...
    config.selected_ids_sha256,config.selected_cell_count, ...
    config.chunk_size,config.max_subdivision_depth, ...
    config.max_fem_refinement_level,config.minimum_cr_mesh_size, ...
    config.minimum_lg_mesh_size,config.fem_refinement_scheme, ...
    config.LG_escalation_policy,config.leaf_acceptance_policy, ...
    config.unverified_leaf_policy, ...
    config.source_git_commit,config.source_git_clean, ...
    config.source_normalized_porcelain_sha256, ...
    config.source_dirty_content_sha256, ...
    config.source_state_sha256);
fingerprint = local_sha256_bytes(uint8(fingerprint_payload));

if isempty(char(opt.run_name))
    run_name = local_default_run_name(config);
else
    run_name = local_safe_name(char(opt.run_name));
end
output_dir = char(opt.output_dir);
run_dir = fullfile(output_dir,run_name);
checkpoint_dir = fullfile(run_dir,'checkpoints');
if ~exist(checkpoint_dir,'dir')
    mkdir(checkpoint_dir);
elseif ~logical(opt.resume)
    existing = dir(fullfile(checkpoint_dir,'chunk_*.mat'));
    if ~isempty(existing)
        error('run_omega_mid_unified_parallel:ExistingCheckpoints', ...
            ['Checkpoints already exist.  Enable resume or choose a ', ...
             'different run_name.']);
    end
end

config_path = fullfile(run_dir,'config.mat');
if exist(config_path,'file')
    saved = load(config_path,'fingerprint');
    if ~isfield(saved,'fingerprint') ...
            || ~strcmp(saved.fingerprint,fingerprint)
        error('run_omega_mid_unified_parallel:ConfigMismatch', ...
            ['The run directory belongs to a different source, input, ', ...
             'selection, or chunk configuration.']);
    end
else
    save(config_path,'config','fingerprint','fingerprint_payload','-v7');
end

% Initialize the client once.  Workers are initialized below before any
% interval cell is dispatched.
omega_up_all_prepare_worker(project_root,mode);
global INTERVAL_MODE
if rigorous && ~logical(INTERVAL_MODE)
    error('run_omega_mid_unified_parallel:IntervalInitFailed', ...
        'The requested interval runtime did not enable INTERVAL_MODE.');
end

chunks = local_build_chunks( ...
    selected_rows,selected_ids,double(opt.chunk_size),checkpoint_dir);
records = cell(selected_count,1);
pending_chunks = zeros(numel(chunks),1);
num_pending_chunks = 0;
num_resumed_records = 0;
retry_failed = logical(opt.retry_failed);

for q = 1:numel(chunks)
    [chunk_records,valid] = local_load_checkpoint( ...
        chunks(q),fingerprint,retry_failed,rigorous, ...
        double(opt.max_subdivision_depth),fem_policy);
    if valid
        first = chunks(q).selected_offset;
        last = first+chunks(q).count-1;
        records(first:last) = chunk_records;
        num_resumed_records = num_resumed_records ...
            + sum(~cellfun(@isempty,chunk_records));
    end
    if ~valid || any(cellfun(@isempty,chunk_records))
        num_pending_chunks = num_pending_chunks+1;
        pending_chunks(num_pending_chunks) = q;
    end
end
pending_chunks = pending_chunks(1:num_pending_chunks);

fprintf(['Omega_mid unified run: selected=%d/%d, chunks=%d, ', ...
    'resumed records=%d, pending chunks=%d\n'], ...
    selected_count,input_count,numel(chunks), ...
    num_resumed_records,numel(pending_chunks));
fprintf('run directory: %s\n',run_dir);

wall_clock = tic;
computed_this_invocation = 0;
if ~isempty(pending_chunks)
    use_parallel = opt.workers > 0 && exist('parpool','file') == 2;
    if opt.workers > 0 && ~use_parallel
        warning('run_omega_mid_unified_parallel:NoParallelToolbox', ...
            'Parallel tools are unavailable; continuing serially.');
    end

    completed_payloads = cell(numel(pending_chunks),1);
    if use_parallel
        pool = gcp('nocreate');
        if isempty(pool) || pool.NumWorkers ~= opt.workers
            if ~isempty(pool)
                delete(pool);
            end
            pool = parpool('local',opt.workers);
        end
        init_future = parfevalOnAll( ...
            pool,@omega_up_all_prepare_worker,0,project_root,mode);
        wait(init_future);
        for f = 1:numel(init_future)
            if ~isempty(init_future(f).Error)
                rethrow(init_future(f).Error);
            end
        end

        chunks_for_workers = chunks;
        parfor k = 1:numel(pending_chunks)
            q = pending_chunks(k);
            completed_payloads{k} = local_execute_chunk( ...
                chunks_for_workers(q),input_file,input_sha256, ...
                fingerprint,rigorous,retry_failed, ...
                double(opt.checkpoint_every), ...
                double(opt.max_subdivision_depth),fem_policy);
        end
    else
        for k = 1:numel(pending_chunks)
            q = pending_chunks(k);
            fprintf('chunk %d/%d (rows %d--%d, cells=%d)\n', ...
                k,numel(pending_chunks), ...
                chunks(q).row_indices(1),chunks(q).row_indices(end), ...
                chunks(q).count);
            completed_payloads{k} = local_execute_chunk( ...
                chunks(q),input_file,input_sha256, ...
                fingerprint,rigorous,retry_failed, ...
                double(opt.checkpoint_every), ...
                double(opt.max_subdivision_depth),fem_policy);
        end
    end

    for k = 1:numel(pending_chunks)
        q = pending_chunks(k);
        payload = completed_payloads{k};
        first = chunks(q).selected_offset;
        last = first+chunks(q).count-1;
        records(first:last) = payload.records;
        computed_this_invocation = computed_this_invocation ...
            + payload.num_computed_this_invocation;
    end
end
wall_seconds = toc(wall_clock);

if any(cellfun(@isempty,records))
    error('run_omega_mid_unified_parallel:IncompleteCheckpointMerge', ...
        'At least one selected input row has no completed record.');
end

input_sha256_after = ver10_file_sha256(input_file);
if ~strcmp(input_sha256,input_sha256_after)
    error('run_omega_mid_unified_parallel:InputChangedDuringRun', ...
        ['The input CSV changed during the run.  Checkpoints from ', ...
         'different input states cannot form one certificate.']);
end
source = ver10_assert_source_unchanged(project_root,source);
source_state_after = local_source_state_digest(project_root);
if ~strcmp(source.source_state_sha256, ...
        source_state_after.source_state_sha256)
    error('run_omega_mid_unified_parallel:SourceContentChangedDuringRun', ...
        ['The normalized Git worktree content digest changed during ', ...
         'the run.  Checkpoints cannot be assembled across source states.']);
end
source.source_state_digest_rechecked_after_run = true;
source.source_state_sha256_after_run = ...
    source_state_after.source_state_sha256;

summary = local_summarize(records,input_ids,selected_ids, ...
    rigorous,full_input_coverage,source,wall_seconds, ...
    num_resumed_records,computed_this_invocation, ...
    double(opt.max_subdivision_depth),fem_policy);

j1_csv_path = fullfile(run_dir,'J1_OmegaMid.csv');
j2_csv_path = fullfile(run_dir,'J2_OmegaMid.csv');
mat_path = fullfile(run_dir,'omega_mid_unified_results.mat');
json_path = fullfile(run_dir,'omega_mid_unified_manifest.json');
local_write_functional_csv(j1_csv_path,records,'J1');
local_write_functional_csv(j2_csv_path,records,'J2');
try
    save(mat_path,'records','config','selection','summary', ...
        'fingerprint','-v7.3');
catch
    save(mat_path,'records','config','selection','summary', ...
        'fingerprint','-v7');
end

manifest = struct();
manifest.schema = 'lowerboundsineq.omega_mid_unified.manifest.v1';
manifest.created_utc = local_utc_timestamp();
manifest.fingerprint = fingerprint;
manifest.mode = mode;
manifest.rigor = local_ternary( ...
    rigorous,'certified_interval','exploratory_double');
manifest.shared_eigenvalue_computation_for_J1_J2 = true;
manifest.source = source;
manifest.runtime = ver10_runtime_metadata();
manifest.config = config;
manifest.input = struct( ...
    'file',ver10_portable_path(project_root,input_file), ...
    'sha256',input_sha256, ...
    'cell_count',input_count, ...
    'cell_ids_sha256',input_ids_sha256, ...
    'validation',input_validation);
manifest.selection = struct( ...
    'mode',selection.mode, ...
    'selected_cell_count',selected_count, ...
    'selected_ids_sha256',selection.selected_ids_sha256, ...
    'target_cell_ids',selection.manifest_cell_ids, ...
    'full_input_coverage',full_input_coverage);
manifest.execution = struct( ...
    'workers_requested',double(opt.workers), ...
    'chunk_size',double(opt.chunk_size), ...
    'checkpoint_every_cells',double(opt.checkpoint_every), ...
    'max_subdivision_depth',double(opt.max_subdivision_depth), ...
    'max_fem_refinement_level',fem_policy.max_refinement_level, ...
    'minimum_cr_mesh_size',fem_policy.minimum_cr_mesh_size, ...
    'minimum_lg_mesh_size',fem_policy.minimum_lg_mesh_size, ...
    'fem_refinement_scheme',fem_policy.scheme, ...
    'LG_escalation_policy',lg_escalation_policy, ...
    'LG_escalation_scope', ...
        ['LG-input rows start with LG; CR-input rows may use LG only ', ...
         'on terminal geometric leaves after all CR refinements fail'], ...
    'leaf_acceptance_policy',leaf_acceptance_policy, ...
    'leaf_acceptance_requirement', ...
        ['every accepted leaf has one strict CR or LG certificate ', ...
         'with finite positive J1 and J2 lower bounds'], ...
    'unverified_leaf_policy',unverified_leaf_policy, ...
    'unverified_leaf_action', ...
        ['any terminal leaf without a strict certificate invalidates ', ...
         'the parent and prevents publication'], ...
    'wall_seconds',wall_seconds);
manifest.summary = summary;
manifest.complete_certificate = summary.complete_certificate;
manifest.resume = struct( ...
    'enabled',logical(opt.resume), ...
    'retry_failed',retry_failed, ...
    'checkpoint_granularity','atomic per-chunk MAT, published after cells', ...
    'checkpoint_directory', ...
        ver10_portable_path(project_root,checkpoint_dir), ...
    'records_loaded',num_resumed_records, ...
    'records_computed_this_invocation',computed_this_invocation);
manifest.files = struct( ...
    'J1_csv',ver10_portable_path(project_root,j1_csv_path), ...
    'J2_csv',ver10_portable_path(project_root,j2_csv_path), ...
    'mat',ver10_portable_path(project_root,mat_path), ...
    'json',ver10_portable_path(project_root,json_path), ...
    'config_mat',ver10_portable_path(project_root,config_path));
manifest.hashes = struct( ...
    'algorithm','SHA-256', ...
    'input',input_sha256, ...
    'J1_csv',ver10_file_sha256(j1_csv_path), ...
    'J2_csv',ver10_file_sha256(j2_csv_path), ...
    'mat',ver10_file_sha256(mat_path), ...
    'config_mat',ver10_file_sha256(config_path));
if rigorous
    manifest.warning = '';
else
    manifest.warning = ...
        'Double output is exploratory and is not a proof certificate.';
end
local_write_json(json_path,manifest, ...
    {project_root,input_file,run_dir,checkpoint_dir});

fprintf(['completed: strict=%d/%d, errors=%d, exact selected IDs=%d, ', ...
    'complete certificate=%d\n'], ...
    summary.num_strict_records,summary.num_selected_cells, ...
    summary.num_errors,summary.exact_selected_id_coverage, ...
    summary.complete_certificate);
fprintf('minimum J1 lower = %.17g\n', ...
    local_printable_number(summary.minimum_J1_lower));
fprintf('minimum J2 lower = %.17g\n', ...
    local_printable_number(summary.minimum_J2_lower));
fprintf('J1 CSV: %s\nJ2 CSV: %s\nJSON: %s\n', ...
    j1_csv_path,j2_csv_path,json_path);
end


function payload = local_execute_chunk( ...
    chunk,input_file,input_sha256,fingerprint,rigorous, ...
    retry_failed,checkpoint_every,max_subdivision_depth,fem_policy)
input_table = local_cached_input_table(input_file,input_sha256);
[records,valid] = local_load_checkpoint( ...
    chunk,fingerprint,retry_failed,rigorous, ...
    max_subdivision_depth,fem_policy);
if ~valid
    records = cell(chunk.count,1);
end

num_computed = 0;
since_checkpoint = 0;
for k = 1:chunk.count
    if ~isempty(records{k})
        continue;
    end
    row_index = chunk.row_indices(k);
    records{k} = local_execute_cell( ...
        input_table,row_index,rigorous, ...
        max_subdivision_depth,fem_policy);
    num_computed = num_computed+1;
    since_checkpoint = since_checkpoint+1;
    if since_checkpoint >= checkpoint_every
        local_save_checkpoint(chunk,fingerprint,records,false);
        since_checkpoint = 0;
    end
end
local_save_checkpoint(chunk,fingerprint,records,true);
payload = struct( ...
    'records',{records}, ...
    'num_computed_this_invocation',num_computed);
end


function record = local_execute_cell( ...
    input_table,row_index,rigorous,max_subdivision_depth,fem_policy)
row = input_table(row_index,:);
record = local_blank_record();
record.cell_id = local_table_number(row,'i');
record.input_row = row_index;
record.x_inf = local_table_number(row,'x_inf');
record.x_sup = local_table_number(row,'x_sup');
record.theta_inf = local_table_number(row,'theta_inf');
record.theta_sup = local_table_number(row,'theta_sup');
record.x_inf_text = local_table_decimal_string(row,'x_inf');
record.x_sup_text = local_table_decimal_string(row,'x_sup');
record.theta_inf_text = local_table_decimal_string(row,'theta_inf');
record.theta_sup_text = local_table_decimal_string(row,'theta_sup');
record.isLG_requested = logical(local_table_number(row,'isLG'));
record.base_mesh_size_cr = ...
    local_table_number(row,'mesh_size_lower_cr');
record.base_mesh_size_lg = ...
    local_table_number(row,'mesh_size_lower_LG');
record.fem_order_lg = ...
    local_table_number(row,'fem_order_lower_LG');
record.rigorous = logical(rigorous);
record.shared_eigenvalue_computation = true;
record.max_subdivision_depth_allowed = max_subdivision_depth;
record.max_fem_refinement_level_allowed = ...
    fem_policy.max_refinement_level;
record.minimum_cr_mesh_size_allowed = ...
    fem_policy.minimum_cr_mesh_size;
record.minimum_lg_mesh_size_allowed = ...
    fem_policy.minimum_lg_mesh_size;
record.fem_refinement_scheme = fem_policy.scheme;
record.subdivision_scheme = ...
    'quadtree-x-theta-outward-overlap-v1';
record.LG_escalation_policy = ...
    'LG-input-or-terminal-depth-after-CR-refinement-v1';
started = tic;

try
    cell_data = local_cell_struct(row);
    [leaves,statistics] = local_certify_node( ...
        cell_data,'',0,max_subdivision_depth, ...
        fem_policy,rigorous);
    record = local_aggregate_parent_record( ...
        record,leaves,statistics,rigorous);
catch ME
    record.computed = false;
    record.status = 'error';
    record.certificate_status = 'error';
    record.error_identifier = ME.identifier;
    record.error_message = ME.message;
end
record.elapsed_seconds = toc(started);
record.completed_utc = local_utc_timestamp();
record.completed = true;
end


function [leaves,statistics] = local_certify_node( ...
    cell_data,path,depth,max_depth,fem_policy,rigorous)
is_lg_requested = logical(local_num_value(cell_data.isLG));
allow_lg_escalation = is_lg_requested || depth >= max_depth;
leaf = local_evaluate_leaf( ...
    cell_data,path,depth,max_depth,fem_policy, ...
    rigorous,allow_lg_escalation);
statistics = struct( ...
    'evaluated_node_count',1, ...
    'spectral_solve_count',leaf.eigenvalue_attempts, ...
    'eigenvalue_total_seconds',leaf.eigenvalue_total_seconds, ...
    'LG_CR_shift_seconds',leaf.LG_CR_shift_seconds, ...
    'LG_fallback_node_count',0, ...
    'LG_analytic_shift_node_count',0, ...
    'LG_CR_Liu_shift_node_count', ...
        double(strcmp(leaf.LG_shift_method,'CR-Liu')), ...
    'direct_CR_node_count',double(strcmp(leaf.method,'CR')));
statistics.LG_fallback_reasons = {};
if leaf.LG_fallback_used && ~isempty(leaf.LG_fallback_reason)
    statistics.LG_fallback_reasons = {leaf.LG_fallback_reason};
end
if leaf.strict_checks_passed || depth >= max_depth
    leaves = leaf;
    return;
end

children = local_split_cell(cell_data);
leaves = repmat(local_blank_leaf(),0,1);
for child_index = 1:4
    child_path = [path,sprintf('%d',child_index)];
    [child_leaves,child_statistics] = local_certify_node( ...
        children(child_index),child_path,depth+1,max_depth, ...
        fem_policy,rigorous);
    leaves = [leaves;child_leaves(:)]; %#ok<AGROW>
    statistics.evaluated_node_count = ...
        statistics.evaluated_node_count ...
        + child_statistics.evaluated_node_count;
    statistics.spectral_solve_count = ...
        statistics.spectral_solve_count ...
        + child_statistics.spectral_solve_count;
    statistics.eigenvalue_total_seconds = ...
        statistics.eigenvalue_total_seconds ...
        + child_statistics.eigenvalue_total_seconds;
    statistics.LG_CR_shift_seconds = ...
        statistics.LG_CR_shift_seconds ...
        + child_statistics.LG_CR_shift_seconds;
    statistics.LG_fallback_node_count = ...
        statistics.LG_fallback_node_count ...
        + child_statistics.LG_fallback_node_count;
    statistics.LG_analytic_shift_node_count = ...
        statistics.LG_analytic_shift_node_count ...
        + child_statistics.LG_analytic_shift_node_count;
    statistics.LG_CR_Liu_shift_node_count = ...
        statistics.LG_CR_Liu_shift_node_count ...
        + child_statistics.LG_CR_Liu_shift_node_count;
    statistics.direct_CR_node_count = ...
        statistics.direct_CR_node_count ...
        + child_statistics.direct_CR_node_count;
    statistics.LG_fallback_reasons = [ ...
        statistics.LG_fallback_reasons, ...
        child_statistics.LG_fallback_reasons]; %#ok<AGROW>
