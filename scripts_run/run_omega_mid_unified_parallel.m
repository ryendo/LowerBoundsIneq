    % Re-derive strictness from numerical and method data.  The manifest
    % never trusts a persisted boolean flag by itself.
    strict(k) = local_record_has_valid_result( ...
        record,rigorous,max_subdivision_depth,fem_policy);
    cert1(k) = logical(local_field(record,'J1_certified',false));
    cert2(k) = logical(local_field(record,'J2_certified',false));
    status = local_field(record,'status','');
    errors(k) = strcmp(status,'error');
    invalid(k) = strcmp(status,'invalid_result');
    method = local_field(record,'method','none');
    method_cr(k) = strcmp(method,'CR');
    method_lg(k) = strcmp(method,'LG');
    method_subdivision(k) = strcmp(method,'SUBDIVISION');
    escalated(k) = logical(local_field(record,'escalated',false));
    leaf_counts(k) = local_field(record,'leaf_count',0);
    max_leaf_depths(k) = local_field(record,'max_leaf_depth',0);
    fem_refined(k) = logical(local_field( ...
        record,'fem_refinement_used',false));
    max_cr_refinement(k) = local_field( ...
        record,'max_cr_refinement_level_used',0);
    max_lg_refinement(k) = local_field( ...
        record,'max_lg_refinement_level_used',-1);
    minimum_cr_mesh(k) = local_field( ...
        record,'minimum_cr_mesh_size_used',NaN);
    minimum_lg_mesh(k) = local_field( ...
        record,'minimum_lg_mesh_size_used',NaN);
    evaluated_nodes(k) = local_field(record,'evaluated_node_count',0);
    spectral_solves(k) = local_field(record,'spectral_solve_count',0);
    eigenvalue_seconds(k) = local_field( ...
        record,'eigenvalue_total_seconds',NaN);
    cr_shift_seconds(k) = local_field( ...
        record,'LG_CR_shift_seconds',NaN);
    fallback_nodes(k) = local_field( ...
        record,'LG_fallback_node_count',0);
    analytic_shift_nodes(k) = local_field( ...
        record,'LG_analytic_shift_node_count',0);
    cr_liu_shift_nodes(k) = local_field( ...
        record,'LG_CR_Liu_shift_node_count',0);
    direct_cr_nodes(k) = local_field(record,'direct_CR_node_count',0);
    shift_method = local_field(record,'LG_shift_method','');
    shift_analytic(k) = false;
    shift_cr_liu(k) = strcmp(shift_method,'CR-Liu');
    shift_mixed(k) = strcmp(shift_method,'mixed');
    shift_not_applicable(k) = strcmp( ...
        shift_method,'not-applicable');
    fallback_used(k) = logical(local_field( ...
        record,'LG_fallback_used',false));
    lg_b_verified_spd(k) = logical(local_field( ...
        record,'LG_B_verified_spd',false));
    j1(k) = local_field(record,'J1_lower',NaN);
    j2(k) = local_field(record,'J2_lower',NaN);
    lambda(k) = local_field(record,'lambda1_lower',NaN);
    separation(k) = local_field( ...
        record,'LG_separation_margin_lower',NaN);
    mu_upper(k) = local_field(record,'LG_mu_upper',NaN);
    rho_lower(k) = local_field(record,'LG_rho_lower',NaN);
    ritz_upper(k) = local_field(record,'LG_ritz_upper',NaN);
    elapsed(k) = local_field(record,'elapsed_seconds',NaN);
end

missing_selected = setdiff(selected_ids(:),record_ids(:));
unexpected = setdiff(record_ids(:),selected_ids(:));
num_duplicate_record_ids = n-numel(unique(record_ids));
exact_selected = isempty(missing_selected) && isempty(unexpected) ...
    && num_duplicate_record_ids == 0 && n == numel(selected_ids);
