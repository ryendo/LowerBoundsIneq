summary.num_nonpositive_J2 = sum(isfinite(j2) & j2 <= 0);
summary.method_counts = struct( ...
    'CR',sum(method_cr), ...
    'LG',sum(method_lg), ...
    'SUBDIVISION',sum(method_subdivision), ...
    'none',sum(~method_cr & ~method_lg & ~method_subdivision), ...
    'escalated_CR_to_LG',sum(escalated));
summary.total_leaf_certificates = sum(leaf_counts);
summary.num_subdivided_parent_cells = sum(method_subdivision);
summary.num_fem_refined_parent_cells = sum(fem_refined);
summary.maximum_leaf_depth = max(max_leaf_depths);
