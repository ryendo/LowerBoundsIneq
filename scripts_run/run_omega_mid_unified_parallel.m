function [records,valid] = local_load_checkpoint( ...
    chunk,fingerprint,retry_failed,expected_rigorous, ...
    max_subdivision_depth,fem_policy)
records = cell(chunk.count,1);
valid = false;
if ~exist(chunk.checkpoint,'file')
    return;
end
try
    payload = load(chunk.checkpoint, ...
        'checkpoint_schema','fingerprint','row_indices', ...
        'expected_cell_ids','records');
    if ~isfield(payload,'checkpoint_schema') ...
            || ~strcmp(payload.checkpoint_schema, ...
                'lowerboundsineq.omega_mid_unified.chunk.v3') ...
            || ~isfield(payload,'fingerprint') ...
            || ~strcmp(payload.fingerprint,fingerprint) ...
            || ~isfield(payload,'row_indices') ...
            || ~isequal(double(payload.row_indices(:)), ...
                double(chunk.row_indices(:))) ...
            || ~isfield(payload,'expected_cell_ids') ...
            || ~isequal(double(payload.expected_cell_ids(:)), ...
                double(chunk.expected_cell_ids(:))) ...
            || ~isfield(payload,'records') ...
            || ~iscell(payload.records) ...
            || numel(payload.records) ~= chunk.count
        return;
    end
    records = payload.records(:);
    for k = 1:chunk.count
        if isempty(records{k})
            continue;
        end
        record = records{k};
        record_valid = isstruct(record) ...
            && logical(local_field(record,'completed',false)) ...
            && local_field(record,'input_row',NaN) ...
                == chunk.row_indices(k) ...
            && local_field(record,'cell_id',NaN) ...
                == chunk.expected_cell_ids(k);
        if ~record_valid
            records{k} = [];
            continue;
        end
        deep_valid = local_record_has_valid_result( ...
            record,expected_rigorous, ...
            max_subdivision_depth,fem_policy);
        % A record that claims success is always revalidated deeply,
        % independently of retry_failed.  The option controls only whether
        % a genuinely failed completed record is retained.
        if ~deep_valid && (retry_failed ...
                || local_record_claims_success(record))
            records{k} = [];
        end
    end
    valid = true;
catch
    records = cell(chunk.count,1);
    valid = false;
end
end


function tf = local_record_has_valid_result( ...
    record,expected_rigorous,max_subdivision_depth,fem_policy)
method = local_field(record,'method','none');
lambda = local_field(record,'lambda1_lower',NaN);
j1 = local_field(record,'J1_lower',NaN);
j2 = local_field(record,'J2_lower',NaN);
tf = logical(local_field(record,'completed',false)) ...
    && logical(local_field(record,'computed',false)) ...
    && logical(local_field(record,'shared_eigenvalue_computation',false)) ...
    && logical(local_field(record,'conditions_verified',false)) ...
    && logical(local_field(record,'strict_checks_passed',false)) ...
    && logical(local_field(record,'J1_positive',false)) ...
    && logical(local_field(record,'J2_positive',false)) ...
    && isfinite(lambda) && lambda > 0 ...
    && isfinite(j1) && j1 > 0 ...
    && isfinite(j2) && j2 > 0 ...
    && any(strcmp(method,{'CR','LG','SUBDIVISION'})) ...
    && local_field(record,'eigenvalue_attempts',0) >= 1;
if ~tf
    return;
end

record_rigorous = logical(local_field(record,'rigorous',false));
if expected_rigorous
    tf = record_rigorous ...
        && logical(local_field(record,'J1_certified',false)) ...
        && logical(local_field(record,'J2_certified',false)) ...
        && logical(local_field(record,'all_certified',false)) ...
        && strcmp(local_field(record,'status',''),'ok') ...
        && strcmp(local_field(record,'certificate_status',''), ...
            'certified_interval');
else
    tf = ~record_rigorous ...
        && strcmp(local_field(record,'status',''), ...
            'exploratory_positive') ...
        && strcmp(local_field(record,'certificate_status',''), ...
            'exploratory_double');
end
if ~tf
    return;
end
tf = local_validate_leaf_tree( ...
    record,expected_rigorous,max_subdivision_depth,fem_policy);
end


function tf = local_record_claims_success(record)
status = local_field(record,'status','');
certificate_status = local_field(record,'certificate_status','');
tf = any(strcmp(status,{'ok','exploratory_positive'})) ...
    || any(strcmp(certificate_status, ...
        {'certified_interval','exploratory_double'})) ...
    || logical(local_field(record,'strict_checks_passed',false)) ...
    || logical(local_field(record,'J1_certified',false)) ...
    || logical(local_field(record,'J2_certified',false)) ...
    || logical(local_field(record,'all_certified',false));
end


function tf = local_leaf_has_valid_result(leaf,expected_rigorous)
method = local_field(leaf,'method','none');
lambda = local_field(leaf,'lambda1_lower',NaN);
j1 = local_field(leaf,'J1_lower',NaN);
j2 = local_field(leaf,'J2_lower',NaN);
tf = logical(local_field(leaf,'completed',false)) ...
    && logical(local_field(leaf,'computed',false)) ...
    && logical(local_field(leaf,'conditions_verified',false)) ...
    && logical(local_field(leaf,'strict_checks_passed',false)) ...
    && logical(local_field(leaf,'J1_positive',false)) ...
    && logical(local_field(leaf,'J2_positive',false)) ...
    && isfinite(lambda) && lambda > 0 ...
    && isfinite(j1) && j1 > 0 ...
    && isfinite(j2) && j2 > 0 ...
    && any(strcmp(method,{'CR','LG'})) ...
    && local_field(leaf,'eigenvalue_attempts',0) >= 1;
if ~tf
    return;
end
shift_method = local_field(leaf,'LG_shift_method','not-recorded');
fallback_used = logical(local_field( ...
    leaf,'LG_fallback_used',false));
fallback_reason = local_field(leaf,'LG_fallback_reason','');
eigenvalue_seconds = local_field( ...
    leaf,'eigenvalue_total_seconds',NaN);
cr_shift_seconds = local_field(leaf,'LG_CR_shift_seconds',NaN);
tf = isfinite(eigenvalue_seconds) && eigenvalue_seconds >= 0 ...
    && isfinite(cr_shift_seconds) && cr_shift_seconds >= 0;
if ~tf
    return;
end
if strcmp(method,'LG')
    rho = local_field(leaf,'LG_rho_lower',NaN);
    ritz = local_field(leaf,'LG_ritz_upper',NaN);
    separation = local_field( ...
        leaf,'LG_separation_margin_lower',NaN);
    mu_upper = local_field(leaf,'LG_mu_upper',NaN);
    tf = isfinite(rho) && rho > 0 ...
        && isfinite(ritz) && ritz > 0 ...
        && rho > ritz ...
        && isfinite(separation) && separation > 0 ...
        && isfinite(mu_upper) && mu_upper < 0 ...
        && logical(local_field(leaf,'LG_B_verified_spd',false)) ...
        && strcmp(shift_method,'CR-Liu') ...
        && ~fallback_used && isempty(fallback_reason);
else
    tf = strcmp(shift_method,'not-applicable') ...
        && ~fallback_used && isempty(fallback_reason) ...
        && cr_shift_seconds == 0;
end
if ~tf
    return;
end
leaf_rigorous = logical(local_field(leaf,'rigorous',false));
if expected_rigorous
    tf = leaf_rigorous ...
        && logical(local_field(leaf,'J1_certified',false)) ...
        && logical(local_field(leaf,'J2_certified',false)) ...
        && logical(local_field(leaf,'all_certified',false)) ...
        && strcmp(local_field(leaf,'status',''),'ok') ...
        && strcmp(local_field(leaf,'certificate_status',''), ...
            'certified_interval');
else
    tf = ~leaf_rigorous ...
        && strcmp(local_field(leaf,'status',''), ...
            'exploratory_positive') ...
        && strcmp(local_field(leaf,'certificate_status',''), ...
            'exploratory_double');
end
end


function tf = local_attempt_history_valid( ...
    leaf,expected_rigorous,max_subdivision_depth,fem_policy)
tf = false;
try
    attempts = local_field(leaf,'attempts',[]);
    if ~isstruct(attempts) || isempty(attempts)
        return;
    end
    attempts = attempts(:);
    schedule_data = struct( ...
        'isLG',double(local_field( ...
            leaf,'isLG_requested',false)), ...
        'mesh_size_lower_cr',local_field( ...
            leaf,'base_mesh_size_cr',NaN), ...
        'mesh_size_lower_LG',local_field( ...
            leaf,'base_mesh_size_lg',NaN));
    [expected_methods,expected_cr_levels,expected_lg_levels] = ...
        local_fem_attempt_schedule( ...
            schedule_data,local_field(leaf,'depth',NaN), ...
            max_subdivision_depth,fem_policy);
    n = numel(attempts);
    if n > numel(expected_methods) ...
            || local_field(leaf,'eigenvalue_attempts',NaN) ~= n
        return;
    end

    for q = 1:n
        expected_cr_mesh = local_refined_mesh_size( ...
            schedule_data.mesh_size_lower_cr, ...
            expected_cr_levels(q), ...
            fem_policy.minimum_cr_mesh_size);
        expected_lg_mesh = local_refined_mesh_size( ...
            schedule_data.mesh_size_lower_LG, ...
            max(expected_lg_levels(q),0), ...
            fem_policy.minimum_lg_mesh_size);
        if local_field(attempts(q),'ordinal',NaN) ~= q ...
                || ~strcmp(local_field( ...
                    attempts(q),'method',''), ...
                    expected_methods{q}) ...
                || local_field(attempts(q), ...
                    'cr_refinement_level',NaN) ...
                    ~= expected_cr_levels(q) ...
                || local_field(attempts(q), ...
                    'lg_refinement_level',NaN) ...
                    ~= expected_lg_levels(q) ...
                || local_field(attempts(q),'mesh_size_cr',NaN) ...
                    ~= expected_cr_mesh ...
                || local_field(attempts(q),'mesh_size_lg',NaN) ...
                    ~= expected_lg_mesh ...
                || ~local_attempt_result_consistent( ...
                    attempts(q),expected_rigorous)
            return;
        end
    end

    strict_attempts = [attempts.strict_checks_passed];
    first_strict = find(strict_attempts,1);
    if isempty(first_strict)
        first_strict = 0;
        if n ~= numel(expected_methods)
            return;
        end
    elseif first_strict ~= n
        % The schedule must stop at the first strict FEM certificate.
        return;
    end
    selected = local_field(leaf,'selected_attempt_ordinal',NaN);
    if selected ~= n ...
            || local_field(leaf,'first_strict_attempt_ordinal',NaN) ...
                ~= first_strict
        return;
    end

    selected_attempt = attempts(selected);
    copied_fields = {'computed','method','conditions_verified', ...
        'lambda1_lower','LG_shift_method','LG_fallback_used', ...
        'LG_fallback_reason','LG_B_verified_spd','LG_rho_lower', ...
        'LG_ritz_upper','LG_separation_margin_lower','LG_mu_upper', ...
        'J1_lower','J2_lower','J1_positive','J2_positive', ...
        'strict_checks_passed','J1_certified','J2_certified', ...
        'all_certified','status','certificate_status', ...
        'error_identifier','error_message'};
    for q = 1:numel(copied_fields)
        name = copied_fields{q};
        if ~isequaln(local_field(leaf,name,[]), ...
                local_field(selected_attempt,name,[]))
            return;
        end
    end
    if local_field(leaf,'cr_refinement_level',NaN) ...
            ~= selected_attempt.cr_refinement_level ...
            || local_field(leaf,'lg_refinement_level',NaN) ...
                ~= selected_attempt.lg_refinement_level ...
            || local_field(leaf,'mesh_size_cr_used',NaN) ...
                ~= selected_attempt.mesh_size_cr ...
            || local_field(leaf,'mesh_size_lg_used',NaN) ...
                ~= selected_attempt.mesh_size_lg ...
            || local_field(leaf,'eigenvalue_total_seconds',NaN) ...
                ~= sum([attempts.eigenvalue_total_seconds]) ...
            || local_field(leaf,'LG_CR_shift_seconds',NaN) ...
                ~= sum([attempts.LG_CR_shift_seconds]) ...
            || logical(local_field(leaf,'escalated',false)) ...
                ~= (~logical(local_field( ...
                    leaf,'isLG_requested',false)) ...
                    && strcmp(selected_attempt.method,'LG'))
        return;
    end
    tf = true;
catch
    tf = false;
end
end


function tf = local_attempt_result_consistent( ...
    attempt,expected_rigorous)
tf = false;
if ~logical(local_field(attempt,'completed',false)) ...
        || logical(local_field(attempt,'rigorous',false)) ...
            ~= logical(expected_rigorous)
    return;
end
eigenvalue_seconds = local_field( ...
    attempt,'eigenvalue_total_seconds',NaN);
cr_shift_seconds = local_field( ...
    attempt,'LG_CR_shift_seconds',NaN);
elapsed_seconds = local_field(attempt,'elapsed_seconds',NaN);
if ~isfinite(eigenvalue_seconds) || eigenvalue_seconds < 0 ...
        || ~isfinite(cr_shift_seconds) || cr_shift_seconds < 0 ...
        || ~isfinite(elapsed_seconds) || elapsed_seconds < 0
    return;
end

computed = logical(local_field(attempt,'computed',false));
if ~computed
    tf = ~logical(local_field( ...
            attempt,'strict_checks_passed',false)) ...
        && ~logical(local_field(attempt,'J1_certified',false)) ...
        && ~logical(local_field(attempt,'J2_certified',false)) ...
        && ~logical(local_field(attempt,'all_certified',false)) ...
        && strcmp(local_field(attempt,'status',''),'error') ...
        && strcmp(local_field( ...
            attempt,'certificate_status',''),'error') ...
        && ~isempty(local_field(attempt,'error_identifier',''));
    return;
end

method = local_field(attempt,'method','none');
lambda = local_field(attempt,'lambda1_lower',NaN);
j1 = local_field(attempt,'J1_lower',NaN);
j2 = local_field(attempt,'J2_lower',NaN);
j1_positive = isfinite(j1) && j1 > 0;
j2_positive = isfinite(j2) && j2 > 0;
conditions = logical(local_field( ...
    attempt,'conditions_verified',false));
if strcmp(method,'CR')
    spectral = conditions ...
        && strcmp(local_field( ...
            attempt,'LG_shift_method',''), ...
            'not-applicable') ...
        && ~logical(local_field( ...
            attempt,'LG_fallback_used',false)) ...
        && isempty(local_field( ...
            attempt,'LG_fallback_reason','')) ...
        && cr_shift_seconds == 0;
elseif strcmp(method,'LG')
    shift_method = local_field( ...
        attempt,'LG_shift_method','');
    fallback = logical(local_field( ...
        attempt,'LG_fallback_used',false));
    fallback_reason = local_field( ...
        attempt,'LG_fallback_reason','');
    rho = local_field(attempt,'LG_rho_lower',NaN);
    ritz = local_field(attempt,'LG_ritz_upper',NaN);
    separation = local_field( ...
        attempt,'LG_separation_margin_lower',NaN);
    mu_upper = local_field(attempt,'LG_mu_upper',NaN);
    shift_consistent = strcmp(shift_method,'CR-Liu') ...
        && ~fallback && isempty(fallback_reason);
    spectral = conditions && shift_consistent ...
        && logical(local_field( ...
            attempt,'LG_B_verified_spd',false)) ...
        && isfinite(rho) && rho > 0 ...
        && isfinite(ritz) && ritz > 0 && rho > ritz ...
        && isfinite(separation) && separation > 0 ...
        && isfinite(mu_upper) && mu_upper < 0;
else
    return;
end
strict = isfinite(lambda) && lambda > 0 ...
    && j1_positive && j2_positive && spectral;
if logical(local_field(attempt,'J1_positive',false)) ...
        ~= j1_positive ...
        || logical(local_field(attempt,'J2_positive',false)) ...
            ~= j2_positive ...
        || logical(local_field( ...
            attempt,'strict_checks_passed',false)) ~= strict
    return;
end
expected_certified = logical(expected_rigorous) && strict;
if logical(local_field(attempt,'J1_certified',false)) ...
        ~= expected_certified ...
        || logical(local_field(attempt,'J2_certified',false)) ...
            ~= expected_certified ...
        || logical(local_field(attempt,'all_certified',false)) ...
            ~= expected_certified
    return;
end
if strict
    if expected_rigorous
        tf = strcmp(local_field(attempt,'status',''),'ok') ...
            && strcmp(local_field( ...
                attempt,'certificate_status',''), ...
                'certified_interval');
    else
        tf = strcmp(local_field( ...
                attempt,'status',''), ...
                'exploratory_positive') ...
            && strcmp(local_field( ...
                attempt,'certificate_status',''), ...
                'exploratory_double');
    end
else
    tf = strcmp(local_field( ...
            attempt,'status',''),'invalid_result') ...
        && strcmp(local_field( ...
            attempt,'certificate_status',''),'invalid');
end
end


function tf = local_validate_leaf_tree( ...
    record,expected_rigorous,max_subdivision_depth,fem_policy)
tf = false;
try
    leaves = local_field(record,'leaves',[]);
    if ~isstruct(leaves) || isempty(leaves)
        return;
    end
    leaves = leaves(:);
    leaf_count = numel(leaves);
    if local_field(record,'leaf_count',NaN) ~= leaf_count ...
            || local_field(record,'max_subdivision_depth_allowed',NaN) ...
                ~= max_subdivision_depth ...
            || local_field(record, ...
                'max_fem_refinement_level_allowed',NaN) ...
                ~= fem_policy.max_refinement_level ...
            || local_field(record, ...
                'minimum_cr_mesh_size_allowed',NaN) ...
                ~= fem_policy.minimum_cr_mesh_size ...
            || local_field(record, ...
                'minimum_lg_mesh_size_allowed',NaN) ...
                ~= fem_policy.minimum_lg_mesh_size ...
            || ~strcmp(local_field(record,'fem_refinement_scheme',''), ...
                fem_policy.scheme) ...
            || ~strcmp(local_field(record,'subdivision_scheme',''), ...
                'quadtree-x-theta-outward-overlap-v1') ...
            || ~strcmp(local_field(record,'LG_escalation_policy',''), ...
                ['LG-input-or-terminal-depth-after-', ...
                 'CR-refinement-v1'])
        return;
    end

    paths = {leaves.path}.';
    if numel(unique(paths)) ~= leaf_count
        return;
    end
    sorted_paths = sort(paths);
    if ~isequal(paths,sorted_paths) ...
            || ~local_complete_path_tree(paths,'')
        return;
    end
    depths = [leaves.depth].';
    if any(depths < 0) || any(depths ~= floor(depths)) ...
            || any(depths > max_subdivision_depth) ...
            || any(depths ~= cellfun(@length,paths)) ...
            || local_field(record,'max_leaf_depth',NaN) ~= max(depths)
        return;
    end
    selected_cr_levels = [leaves.cr_refinement_level];
    selected_lg_levels = [leaves.lg_refinement_level];
    expected_fem_refinement = any(selected_cr_levels > 0) ...
        || any(selected_lg_levels > 0);
    lg_selected = strcmp({leaves.method},'LG');
    if any(lg_selected)
        expected_min_lg_mesh = ...
            min([leaves(lg_selected).mesh_size_lg_used]);
    else
        expected_min_lg_mesh = NaN;
    end
    if logical(local_field(record, ...
            'fem_refinement_used',false)) ...
            ~= expected_fem_refinement ...
            || local_field(record, ...
                'max_cr_refinement_level_used',NaN) ...
                ~= max(selected_cr_levels) ...
            || local_field(record, ...
                'max_lg_refinement_level_used',NaN) ...
                ~= max(selected_lg_levels) ...
            || local_field(record, ...
                'minimum_cr_mesh_size_used',NaN) ...
                ~= min([leaves.mesh_size_cr_used]) ...
            || ~isequaln(local_field(record, ...
                'minimum_lg_mesh_size_used',NaN), ...
                expected_min_lg_mesh)
        return;
    end

    root = struct( ...
        'x_inf',local_field(record,'x_inf_text',''), ...
        'x_sup',local_field(record,'x_sup_text',''), ...
        'theta_inf',local_field(record,'theta_inf_text',''), ...
        'theta_sup',local_field(record,'theta_sup_text',''));
    for k = 1:leaf_count
        expected_cell = local_follow_path(root,paths{k});
        [x_lo,x_hi,t_lo,t_hi] = local_cell_enclosure(expected_cell);
        if leaves(k).x_inf ~= x_lo ...
                || leaves(k).x_sup ~= x_hi ...
                || leaves(k).theta_inf ~= t_lo ...
                || leaves(k).theta_sup ~= t_hi ...
                || logical(local_field( ...
                    leaves(k),'isLG_requested',false)) ...
                    ~= logical(local_field( ...
                        record,'isLG_requested',false)) ...
                || local_field(leaves(k), ...
                    'base_mesh_size_cr',NaN) ...
                    ~= local_field(record, ...
                        'base_mesh_size_cr',NaN) ...
                || local_field(leaves(k), ...
                    'base_mesh_size_lg',NaN) ...
                    ~= local_field(record, ...
                        'base_mesh_size_lg',NaN) ...
                || local_field(leaves(k),'fem_order_lg',NaN) ...
                    ~= local_field(record,'fem_order_lg',NaN) ...
                || logical(local_field( ...
                    leaves(k),'LG_escalation_allowed',false)) ...
                    ~= (logical(local_field( ...
                        leaves(k),'isLG_requested',false)) ...
                        || leaves(k).depth >= max_subdivision_depth) ...
                || ~local_attempt_history_valid( ...
                    leaves(k),expected_rigorous, ...
                    max_subdivision_depth,fem_policy) ...
                || ~local_leaf_has_valid_result( ...
                    leaves(k),expected_rigorous)
            return;
        end
    end

    subdivision_used = any(depths > 0);
    expected_method = local_ternary( ...
        subdivision_used,'SUBDIVISION',leaves(1).method);
    expected_node_count = (4*leaf_count-1)/3;
    leaf_attempts = sum([leaves.eigenvalue_attempts]);
    maximum_attempts_per_node = ...
        2*(fem_policy.max_refinement_level+1);
    evaluated_nodes = local_field(record,'evaluated_node_count',NaN);
    spectral_solves = local_field(record,'spectral_solve_count',NaN);
    eigenvalue_seconds = local_field( ...
        record,'eigenvalue_total_seconds',NaN);
    cr_shift_seconds = local_field( ...
        record,'LG_CR_shift_seconds',NaN);
    fallback_nodes = local_field( ...
        record,'LG_fallback_node_count',NaN);
    analytic_nodes = local_field( ...
        record,'LG_analytic_shift_node_count',NaN);
    cr_liu_nodes = local_field( ...
        record,'LG_CR_Liu_shift_node_count',NaN);
    direct_cr_nodes = local_field( ...
        record,'direct_CR_node_count',NaN);
    shift_statistics = struct( ...
        'LG_analytic_shift_node_count',analytic_nodes, ...
        'LG_CR_Liu_shift_node_count',cr_liu_nodes);
    expected_shift_method = ...
        local_aggregate_shift_method(shift_statistics);
    fallback_reason = local_field( ...
        record,'LG_fallback_reason','');
    if ~strcmp(local_field(record,'method',''),expected_method) ...
            || logical(local_field(record,'subdivision_used',false)) ...
                ~= subdivision_used ...
            || evaluated_nodes ~= expected_node_count ...
            || spectral_solves < evaluated_nodes ...
            || spectral_solves ...
                > maximum_attempts_per_node*evaluated_nodes ...
            || spectral_solves < leaf_attempts ...
            || local_field(record,'eigenvalue_attempts',NaN) ...
                ~= spectral_solves ...
            || ~isfinite(eigenvalue_seconds) ...
            || eigenvalue_seconds < 0 ...
            || eigenvalue_seconds ...
                < sum([leaves.eigenvalue_total_seconds]) ...
            || ~isfinite(cr_shift_seconds) ...
            || cr_shift_seconds < 0 ...
            || cr_shift_seconds ...
                < sum([leaves.LG_CR_shift_seconds]) ...
            || any(~isfinite([fallback_nodes,analytic_nodes, ...
                cr_liu_nodes,direct_cr_nodes])) ...
            || any([fallback_nodes,analytic_nodes, ...
                cr_liu_nodes,direct_cr_nodes] < 0) ...
            || any([fallback_nodes,analytic_nodes, ...
                cr_liu_nodes,direct_cr_nodes] ~= floor( ...
                    [fallback_nodes,analytic_nodes, ...
                     cr_liu_nodes,direct_cr_nodes])) ...
            || fallback_nodes ~= 0 ...
            || analytic_nodes ~= 0 ...
            || cr_liu_nodes+direct_cr_nodes ...
                > evaluated_nodes ...
            || ~strcmp(local_field( ...
                record,'LG_shift_method',''), ...
                expected_shift_method) ...
            || logical(local_field( ...
                record,'LG_fallback_used',false)) ...
            || ~isempty(fallback_reason)
        return;
    end
    for k = 1:leaf_count
        if leaves(k).LG_fallback_used ...
                && ~contains(fallback_reason, ...
                    leaves(k).LG_fallback_reason)
            return;
        end
    end

    if local_field(record,'lambda1_lower',NaN) ...
            ~= min([leaves.lambda1_lower]) ...
            || local_field(record,'J1_lower',NaN) ...
                ~= min([leaves.J1_lower]) ...
            || local_field(record,'J2_lower',NaN) ...
                ~= min([leaves.J2_lower])
        return;
    end
    lg = strcmp({leaves.method},'LG');
    if any(lg)
        if ~logical(local_field( ...
                    record,'LG_B_verified_spd',false)) ...
                || local_field(record,'LG_rho_lower',NaN) ...
                ~= min([leaves(lg).LG_rho_lower]) ...
                || local_field(record,'LG_ritz_upper',NaN) ...
                    ~= max([leaves(lg).LG_ritz_upper]) ...
                || local_field(record, ...
                    'LG_separation_margin_lower',NaN) ...
                    ~= min([leaves(lg).LG_separation_margin_lower]) ...
                || local_field(record,'LG_mu_upper',NaN) ...
                    ~= max([leaves(lg).LG_mu_upper])
            return;
        end
    elseif ~logical(local_field( ...
            record,'LG_B_verified_spd',false))
        return;
    end
    tf = true;
catch
    tf = false;
end
end


function tf = local_complete_path_tree(paths,prefix)
exact = strcmp(paths,prefix);
descendant = startsWith(paths,prefix);
subtree_paths = paths(descendant);
if any(exact)
    tf = numel(subtree_paths) == 1;
    return;
end
tf = ~isempty(subtree_paths);
if ~tf
    return;
end
for child = 1:4
    child_prefix = [prefix,sprintf('%d',child)];
    if ~local_complete_path_tree(subtree_paths,child_prefix)
        tf = false;
        return;
    end
end
end


function cell_data = local_follow_path(root,path)
cell_data = root;
for k = 1:length(path)
    children = local_split_cell(cell_data);
    child = str2double(path(k));
    if ~isfinite(child) || child < 1 || child > 4
        error('run_omega_mid_unified_parallel:BadLeafPath', ...
            'Leaf paths must contain only digits 1--4.');
    end
    cell_data = children(child);
end
end


