function upper_write_results_csv(filename, results)
%UPPER_WRITE_RESULTS_CSV Write machine-readable cell certificate summary.
fid = fopen(filename, 'w');
if fid < 0
    error('Cannot open %s for writing.', filename);
end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid, ['cell_id,mode,rigor,verified,x_lo,x_hi,y_lo,y_hi,', ...
    'backend,mesh_order,trial_resolution,lambda_ritz_midpoint,', ...
    'rayleigh_lower,rayleigh_upper,', ...
    'target_lower,target_upper,margin_lower,margin_upper,', ...
    'natural_margin_lower,natural_margin_upper,enclosure\n']);
for k = 1:numel(results)
    r = results{k};
    fprintf(fid, ['%d,%s,%s,%d,%.17g,%.17g,%.17g,%.17g,%s,%d,%d,', ...
        '%.17g,%.17g,%.17g,%.17g,%.17g,%.17g,%.17g,', ...
        '%.17g,%.17g,%s\n'], ...
        r.cell_id, r.mode, r.rigor, r.verified, ...
        r.x_lo, r.x_hi, r.y_lo, r.y_hi, r.backend, ...
        r.mesh_order, r.trial_resolution, ...
        r.lambda_ritz_midpoint, r.rayleigh_lower, r.rayleigh_upper, ...
        r.target_lower, r.target_upper, r.margin_lower, r.margin_upper, ...
        r.natural_margin_lower, r.natural_margin_upper, r.enclosure);
end
end
